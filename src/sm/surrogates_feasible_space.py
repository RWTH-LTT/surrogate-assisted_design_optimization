""" Module to predict the feasibility of input data points with a linear program (LP).
The LP checks if the input data point lies within the convex hull of a set of vertices,
which where generated by using sm.feasible_space_expl.Convex_Hull_Explorer
"""
import os
import time
import numpy as np
import pandas as pd
from scipy.optimize import linprog
from core.helpers import get_process_names, get_config_file, get_input_file, get_data_out
from core.ts_scaling import get_ts_scaling_names, get_ts_scaling_key

class Feasibility_LP():
    """ Class to predict the feasibility of input data points with a linear program (LP).
    The LP checks if the input data point lies within the convex hull of a set of vertices,
    which where generated by using sm.feasible_space_expl.Convex_Hull_Explorer
    """
    def __init__(self, data_in_path:str, project_file:str, df_vertices:pd.DataFrame) -> None:
        """     
        Args:
            data_in_path (str): path to the input files, where the project file lies
            project_file (str): name of the .yaml file in data_in_path containing the
                input information (e.g. project.yaml)
        """
        self.data_in_path = data_in_path
        self.project_file = project_file

        self.min_dict, self.max_dict = self._build_min_max_dict()

        self.vertices = self._get_vertices(df_vertices)
        self.number_of_vertices = self.vertices.shape[0]

        # Get process and demand_scaling names:
        self.input_names_process = get_process_names(
            self.data_in_path, self.project_file,
            only_feasibility_affecting=True, storage_or_production='both')
        self.input_names_timeseries = get_ts_scaling_names(
            self.data_in_path, self.project_file,
            only_feasibility_affecting=True, which_ts_scale_mode='all')
        self.input_names_complete = self.input_names_process + self.input_names_timeseries

    def predict_feasibility(self, df_in:pd.DataFrame) -> tuple:
        """ Predict the feasibility of input data points.

        Args:
            df_in (pd.DataFrame): DataFrame containing the input data points to be checked.
                The DataFrame must contain the columns for all processes and timeseries

        Returns:
            tuple: (feasibility_list, dt) where feasibility_list is a list of booleans
                indicating the feasibility of each input data point and dt is a list of
                the solving times for each input data point
        """
        # Copy input:
        df_in = df_in.copy()

        # Normalize the input data:
        df_in = self._normalize_input_data(df_in)

        # Extract input data from df_in:
        # (The order is important and must be equal to the order of column_names in 
        # self._get_A_matrix and thus equal to the order implemented in get_result_column_name)
        input_data = df_in[self.input_names_complete].to_numpy()

        # Initiliaze arrays to track the feaisbility and the solving time
        feasibility_list = []
        dt = []

        # Loop over input data sample by sample:
        for idx, point in enumerate(input_data): # (point is an 1D np array)

            if idx % 100 == 0:
                print(f"{idx} / {len(df_in)}", flush=True)

            # Start timer:
            t0 = time.time()

            # Solve feasibility LP
            feasibility = self._solve_feasibility_lp(point)

            # Add solving time and feasiblity to list
            dt.append(time.time() - t0)
            feasibility_list.append(feasibility)

        return (feasibility_list, dt)

    def _solve_feasibility_lp(self, point:np.array) -> bool:
        """ Solve the feasibility linear program (LP) for one input data point.

        Args:
            point (np.array): 1D np array containing the input data point to be checked

        Returns:
            bool: True if the point is feasible, False otherwise
        """
        # objective - irrelevant, da nur check bedeutend
        c = np.zeros(self.number_of_vertices)

        # constraints
        A_eq = np.vstack([self.vertices.T, np.ones(self.vertices.shape[0])])
        b_eq = np.append(point,1)

        # bounds
        bounds = [(0,1)] * self.number_of_vertices

        result = linprog(c, A_eq = A_eq, b_eq = b_eq, bounds = bounds, method='highs')

        return result['success']

    def _build_min_max_dict(self) -> tuple:
        """Build the min and the max dict from the min and max values from the input.yaml files.
        The min_dict and max_dict have the column names for the respective values as keys and are
        therefore more convinient to handle, compared to the process or product names

        Returns:
            tuple: (min_dict, max_dict), e.g.{'B': 0, 'demand_heat_mean': 0}
        """

        min_values, max_values = get_min_max_values(self.data_in_path, self.project_file)

        min_dict = {}
        max_dict = {}

        # Check, that all categories contain the same keys:
        for category in min_values.keys():
            assert set(min_values[category].keys()) == set(max_values[category].keys())

        ### Production processes
        production_af = get_process_names(
            self.data_in_path, self.project_file,
            only_feasibility_affecting=True, storage_or_production='production')
        assert(set(production_af) == set(min_values['production'].keys()))

        for process in production_af:
            min_dict[process] = min_values['production'][process]
            max_dict[process] = max_values['production'][process]

        ### Storage processes
        storage_af = get_process_names(
            self.data_in_path, self.project_file,
            only_feasibility_affecting=True, storage_or_production='storage')
        assert(set(storage_af) == set(min_values['storage'].keys()))

        for process in storage_af:
            min_dict[process] = min_values['storage'][process]
            max_dict[process] = max_values['storage'][process]

        ### Demand mean products
        demand_mean_af = get_ts_scaling_names(
            self.data_in_path, self.project_file,
            only_feasibility_affecting=True, which_ts_scale_mode='mean')
        # Extract product name ('demand_heat_mean' -> 'heat')
        products = [key.split('_')[1] for key in demand_mean_af]

        assert(set(products) == set(min_values['demand_mean'].keys()))

        for key in demand_mean_af:
            min_dict[key] = min_values['demand_mean'][key.split('_')[1]]
            max_dict[key] = max_values['demand_mean'][key.split('_')[1]]

        ### Demand mean products
        demand_peak_af = get_ts_scaling_names(
            self.data_in_path, self.project_file,
            only_feasibility_affecting=True, which_ts_scale_mode='peak')
        # Extract product name ('demand_heat_mean' -> 'heat')
        products = [key.split('_')[1] for key in demand_peak_af]

        assert(set(products) == set(min_values['demand_peak'].keys()))

        for key in demand_peak_af:
            min_dict[key] = min_values['demand_peak'][key.split('_')[1]]
            max_dict[key] = max_values['demand_peak'][key.split('_')[1]]

        return min_dict, max_dict

    def _get_vertices(self, df_vertices:pd.DataFrame) -> np.array:
        """ Extracts the vertices from the df_vertices DataFrame and removes duplicate rows.

        Args:
            df_vertices (pd.DataFrame): DataFrame containing the vertex points

        Returns:
            np.array: 2D np array containing the unique vertex points
        """
        # Get column names of the normalized results:
        column_names_norm = get_result_column_names(
            self.data_in_path, self.project_file, normed_keys=True)

        # Remove non-unique data points:
        df_unique = df_vertices.drop_duplicates(
            subset=column_names_norm, keep='first')

        # Check: everything unique?
        if len(df_unique) != len(df_vertices):
            n = len(df_vertices) - len(df_unique)
            print(f"df_vertices contained '{n}' doublicate rows, which are now removed")

        # Get vertices
        return df_unique[column_names_norm].to_numpy()

    def _normalize_input_data(self, df_in:pd.DataFrame) -> pd.DataFrame:
        """ Normalizes the input data in df_in with the min and max values from the input.yaml files

        Args:
            df_in (pd.DataFrame): DataFrame containing the input data points to be checked.

        Returns:
            pd.DataFrame: DataFrame containing the normalized input data points
        """
        # Normalize Processes, Demand Mean and Demand Peak
        for input_name in self.input_names_complete:
            df_in[input_name] = (
                (df_in[input_name] - self.min_dict[input_name])/
                (self.max_dict[input_name]- self.min_dict[input_name])
                ).values

        return df_in

def get_result_column_names(data_in_path, project_file:str, normed_keys:bool=True) -> list:
    """ Generates list of strings of the result column names.

    Args:
        normed_keys (bool, optional): If True: Column names of the normalized results are
            returned. If False: Column names of the non normalized results are returned.
            Defaults to True.

    Returns:
        list: list of strings of the result column names
    """
    normed = "_norm" if normed_keys else ""

    process_af = get_process_names(
        data_in_path, project_file, only_feasibility_affecting=True, storage_or_production='both')

    timeseries_af = get_ts_scaling_names(
        data_in_path,
        project_file,
        only_feasibility_affecting=True,
        which_ts_scale_mode='all')

    return [f"res_{n}{normed}" for n in process_af + timeseries_af]

def get_min_max_values(data_in_path:str, project_file:str) -> tuple:
    """ Contructs min_values and max_values with extreme values determined by the input .yaml files
    """

    # Load input from .yaml files:
    technologies = get_input_file(data_in_path, project_file, 'technologies')['technologies']
    config = get_config_file(data_in_path, project_file)
    ts_scaling = get_input_file(data_in_path, project_file, 'timeseries_scaling')[
        'timeseries_scaling'][config['timeseries_scaling']]

    # Initialize min values:
    min_values = {
        'production' : {},
        'storage' : {},
        'demand_mean' : {},
        'demand_peak' : {}
        }
    # Initialize max values:
    max_values = {
        'production' : {},
        'storage' : {},
        'demand_mean' : {},
        'demand_peak' : {}
        }

    # Production processes:
    process_names = get_process_names(data_in_path, project_file, True, 'production')
    for d in process_names:
        # Set min value to 0
        min_values['production'][d] = 0

        # Set max value to max value from technologies:
        max_values['production'][d] = technologies[d]['potential_capacity_kW']

    # Storage processes:
    process_names = get_process_names(data_in_path, project_file, True, 'storage')
    for d in process_names:
        # Set min value to 0
        min_values['storage'][d] = 0

        # Set max value to max value from technologies:
        max_values['storage'][d] = technologies[d]['potential_capacity_kWh']

    # Demand mean values:
    ts_scaling_names = get_ts_scaling_names(data_in_path, project_file, True, 'mean')
    for ts_scaling_name in ts_scaling_names:
        product = ts_scaling_name.split('_')[1]

        # Set min value to 0
        min_values['demand_mean'][product] = 0

        key = get_ts_scaling_key({'ts_type':'demand', 'product_or_process': product}, ts_scaling)
        # Set max value to max value from ts_scaling:
        max_values['demand_mean'][product] = ts_scaling[key]['param']['mean']['max']

    # Demand peak values:
    ts_scaling_names = get_ts_scaling_names(data_in_path, project_file, True, 'peak')
    for ts_scaling_name in ts_scaling_names:
        product = ts_scaling_name.split('_')[1]

        # Set min value to 0
        min_values['demand_peak'][product] = 0

        key = get_ts_scaling_key({'ts_type':'demand', 'product_or_process': product}, ts_scaling)
        # Set max value to max value from ts_scaling:
        max_values['demand_peak'][product] = ts_scaling[key]['param']['peak']['max']

    return min_values, max_values

def save_unique_vertex_points(
        data_in_path:str, project_file:str, full_vertex_csv_name:str, unique_vertex_name:str,
        n_unique_list:list=None, add_all_unique_vertices:bool=False) -> None:
    """ reads vertex result csv, filters for unique vertices and saves filtered dataframes with
    only unique vertices

    Args:
        data_in_path (str): path to the input files, where the project file lies
        project_file (str): name of the .yaml file in data_in_path containing the
            input information (e.g. project.yaml)
        full_vertex_csv_name (str): name of the full vertex.CSV which lies in DATA_OUT
        unique_vertex_name (str): name of the filtered.CSV files
        n_unique_list (list, optional): list of ints. Defaults to [5000].
        add_all_unique_vertices (bool, optional): If all unique points should be saved.
            Defaults to False.
    """
    # Set default value (Done manually, as [] is a "dangerous default value"):
    if n_unique_list is None:
        n_unique_list = [5000]

    data_out = get_data_out(data_in_path, project_file)

    df_full_vertex = pd.read_csv(
        os.path.join(data_out, full_vertex_csv_name.removesuffix('.csv') + '.csv'), index_col='id')

    # Filter out doublicates:
    column_names_norm = get_result_column_names(data_in_path, project_file, normed_keys=True)

    df_unique = df_full_vertex.drop_duplicates(subset=column_names_norm, keep='first')

    # Add len(df) to n_unique_list if add_all_unique_vertices
    if add_all_unique_vertices:
        n_unique_list.append(len(df_unique))

    for n_unique in n_unique_list:
        output_path = os.path.join(
            data_out, unique_vertex_name.removesuffix('.csv')+f'_{int(n_unique)}.csv')

        df_unique[:int(n_unique)].to_csv(output_path, index=False)
        print(f"Saved '{n_unique}' unique vertex points to '{output_path}'.", flush=True)

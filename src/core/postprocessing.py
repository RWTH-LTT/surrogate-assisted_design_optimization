def get_variable_sum(model, model_instance_variable):
    """ Returns the sum of the values of a pyomo.Var of all indices.
    
    If the variable is indexed by 't', the values are multiplied by the
    respective weights from the time slice before summing. This is done,
    to multiply time-dependend values with their weight in order to 
    reaggregate the data
    
    Args:
        model (pyomo.environ.ConcreteModel): solved pyomo model
        model_instance_variable (pyomo.core.base.var.IndexedVar): Indexed Variable of a solved
            pyomo model
    
    Returns:
        float: sum of all entries of model_instance_variable
    """
    index_set = model_instance_variable.index_set()
    weights = dict(model.time_slice_weight.items())

    # Find the position of 't' in the index set, if it exists
    t_position = next(
        (i for i, idx_set in enumerate(index_set.subsets()) if idx_set == model.t),
        None,
    )

    # Sum values with or without applying weights based on the presence of 't'
    if t_position is not None:
        # 't' is part of the index, so apply weights
        return sum(
            model_instance_variable[index].value * weights[index[t_position]]
            for index in model_instance_variable
        )
    else:
        # 't' is not part of the index, no weights applied
        return sum(
            model_instance_variable[index].value
            for index in model_instance_variable
        )

def get_variable_sum_for_product(model, model_instance_variable, product:str):
    """ Get the sum of the model_instance_variable for a certain product from the model

    Args:
        model (pyomo.environ.ConcreteModel): solved pyomo model
        model_instance_variable (pyomo.core.base.var.IndexedVar):
            Indexed Variable of a solved pyomo model
        product (str): name of the product, for which the sum should be calculated

    Raises:
        ValueError: If the product is not in the model.products
        IndexError: If the index 't' or 'products' does not occur in model_instance_variable

    Returns:
        float: sum of the model_instance_variable for the product
    """
    if product not in list(model.products):
        raise ValueError(f"product '{product}' is not in model.products: {list(model.products)}")

    # Get the index set of the variable:
    index_set = model_instance_variable.index_set()

    # Find the position of 't' in the index set, if it exists:
    t_position = next(
        (i for i, idx_set in enumerate(index_set.subsets()) if idx_set == model.t),
        None,
    )
    if t_position is None:
        raise IndexError(
            "The index 't' does not occur in model_instance_variable. Something went wrong.")

    # Find the position of 'products' in the index set, if it exists:
    product_position = next(
        (i for i, idx_set in enumerate(index_set.subsets()) if idx_set == model.products),
        None,
    )
    if product_position is None:
        raise IndexError(
            "The index 'products' does not occur in model_instance_variable. Something went wrong.")

    # Get the weights for the time slices:
    weights = dict(model.time_slice_weight.items())

    # Sum over all values of the product:
    return sum(
        model_instance_variable[index].value * weights[index[t_position]]
        for index in model_instance_variable
        if index[product_position] == product
        )

def get_variable_sum_for_production_process(model, model_instance_variable, process_prod:str):
    """ Get the sum of the model_instance_variable for a certain process from the model

    Args:
        model (pyomo.environ.ConcreteModel): solved pyomo model
        model_instance_variable (pyomo.core.base.var.IndexedVar):
            Indexed Variable of a solved pyomo model
        process_prod (str): name of the production process

    Raises:
        ValueError: If the product is not in the model.products
        IndexError: If the index 't' or 'products' does not occur in model_instance_variable

    Returns:
        float: sum of the model_instance_variable for the product
    """
    if process_prod not in list(model.processes_production):
        raise ValueError(
            f"process_prod '{process_prod}' is not in model.processes_production: "+
            f"({list(model.processes_production)}")

    # Get the index set of the variable:
    index_set = model_instance_variable.index_set()

    # Find the position of 't' in the index set, if it exists:
    t_position = next(
        (i for i, idx_set in enumerate(index_set.subsets()) if idx_set == model.t),
        None,
    )
    if t_position is None:
        raise IndexError(
            "The index 't' does not occur in model_instance_variable. Something went wrong.")

    # Find the position of 'process' in the index set, if it exists:
    process_position = next(
        (i for i, idx_set in enumerate(index_set.subsets())
         if idx_set == model.processes_production),
        None,
    )
    if process_position is None:
        raise IndexError(
            "The index 'processes_production' does not occur in model_instance_variable. "+
            "Something went wrong.")

    # Get the weights for the time slices:
    weights = dict(model.time_slice_weight.items())

    # Sum over all values of the product:
    return sum(
        model_instance_variable[index].value * weights[index[t_position]]
        for index in model_instance_variable
        if index[process_position] == process_prod
        )

def get_full_load_hours(model, process_prod:str):
    """ Calculate the full load hours for a certain production process

    Args:
        model (pyomo.environ.ConcreteModel): solved pyomo model
        process_prod (str): name of the production process

    Returns:
        float: full load hours for the production process
    """
    nominal_capacity = model.Production_nominal_capacity[process_prod].value
    # If no process in build, return 0 (to avoid division by zero):
    if nominal_capacity == 0:
        return 0

    total_load = get_variable_sum_for_production_process(
        model, model.Production_load, process_prod
    )
    return total_load / nominal_capacity

    def _convert_to_dataframe(self, output_dict:dict, products_or_processes:list, category:str,
                              scenario_name: str = None):
        """  Convert a dictionary from tuple format in Pyomo into a DataFrame.

        Args:
            output_dict (dict): generated by PostProcessor
            products_or_processes (list): e.g., ['electricity', 'heat']
            category (str): The category (key) of the output_dict (e.g., 'Demand')
            scenario_name (str): Name of the scenario of choice (e.g., 'base'). Defaults to None.

        Returns:
            pd.DataFrame: '(key_1, category)', ...b '(key_n, category)' as headers
                time steps as rows.
        """
        # Initiliaze dict with empty list for each product
        product_data = {(product): [] for product in products_or_processes}

        # Iterate over desired subdict
        for key, value in output_dict[category].items():
            product_name = key[0]

            # If a scenario_name is given, check that its the correct scenario:
            if scenario_name is not None:
                if scenario_name != key[2]:
                    continue

            if product_name in products_or_processes:
                product_data[(product_name)].append(value)

        return pd.DataFrame(product_data)


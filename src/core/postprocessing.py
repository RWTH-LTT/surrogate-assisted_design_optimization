    def _get_cost_table(self, scenario:str):
        """ Creates a cost summary table."""
        tac = self.output_dict['TAC'][None]
        capex = self.output_dict['CAPEX'][scenario]
        opex_total = self.output_dict['OPEX'][scenario]

        # Loop over products to get OPEX for lost load and opex for purchasing energy
        cost_lostload_list = []
        cost_buying_list = []
        cost_selling_list = []

        for product in self.products:
            # Purchased Energy
            products_buy_df = self.output_dict['Products_buy'].loc[product,:,scenario].values
            price_buy_df    = self.output_dict['pricebuy_scaled'].loc[product,:,scenario].values
            cost_buying_list.append(
                sum(self.output_dict['time_slice_weight'].values * products_buy_df * price_buy_df)
                )

            # Sold energy
            products_sell_df = self.output_dict['Products_sell'].loc[product,:,scenario].values
            price_sell_df    = self.output_dict['pricesell_scaled'].loc[product,:,scenario].values
            cost_selling_list.append(
                sum(self.output_dict['time_slice_weight'].values * products_sell_df * price_sell_df)
                )

            # Value of lost load
            lostload = self.output_dict['Products_lost_load'][product,:,scenario].values
            value_of_lostload = self.output_dict['value_of_lost_load'][product]
            cost_lostload_list.append(
                sum(self.output_dict['time_slice_weight'].values * lostload) * value_of_lostload
                )

        # Loop over production processes to get their investment cost
        invest_production = [
            self.output_dict['Production_nominal_capacity'][process]
            * self.output_dict['production_investment_cost'][process, scenario]
            for process in self.production_processes
        ]

        # Loop over storage processes to get their investment cost
        invest_storage = [
            self.output_dict['Storage_nominal_capacity'][process]
            * self.output_dict['storage_investment_cost'][process, scenario]
            for process in self.storage_processes
        ]

        # Loop over production processes to get their maintenance cost
        maintenance_production = [
            self.output_dict['Production_nominal_capacity'][process]
            * self.output_dict['production_maintenance_cost'][process, scenario] / 100
            for process in self.production_processes
        ]

        # Loop over storage processes to get their maintenance cost
        maintenance_storage = [
            self.output_dict['Storage_nominal_capacity'][process]
            * self.output_dict['storage_maintenance_cost'][process, scenario] / 100
            for process in self.storage_processes
        ]

        data = {
            'tac'                    : [f"{tac:.4e}"],
            'capex'                  : [f"{capex:.4e}"],
            'opex'                   : [f"{opex_total:.4e}"],
            'overcapacity'           : [f"{self.output_dict['Overcapacity'][None]*100:.2f}"],
            'cost_lostload'          : [f"{sum(cost_lostload_list):.4e}"],
            'cost_buying'            : [f"{sum(cost_buying_list):.4e}"],
            'cost_selling_list'      : [f"{sum(cost_selling_list):.4e}"],
            'invest_production'      : [f"{sum(invest_production):.4e}"],
            'invest_storage'         : [f"{sum(invest_storage):.4e}"],
            'maintenance_production' : [f"{sum(maintenance_production):.4e}"],
            'maintenance_storage'    : [f"{sum(maintenance_storage):.4e}"],
        }

        source = ColumnDataSource(data)

        # Custom CSS to add right borders to some columns
        template = """
            <div style="border-right: 2px solid black; padding-right: 5px;">
                <%= value %>
            </div>
        """

        border_formatter = HTMLTemplateFormatter(template=template)

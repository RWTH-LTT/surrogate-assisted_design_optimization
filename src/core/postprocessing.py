class PostProcessor():
    """ Class for post-processing optimization results. """
    def __init__(self, project_file: str, data_in_path:str, model, result):
        """
        Args:
            data_in_path (str): path to the input files, where the project file lies
            project_file (str): name of the .yaml file in data_in_path containing the
                input information (e.g. project.yaml)
            model (pyomo.environ.ConcreteModel): Pyomo model generated by optimization_MILP
            result: Results generated by solving pyomo model
        """

        self.data_in_path = data_in_path
        self.project_file = project_file
        assert os.path.exists(self.data_in_path)
        self._load_general_input_yamls()

        self.model = model
        self.result = result
        self.probability = dict(model.probability.items())
        self.scenarios = model.scenarios[None].data()
        self.output_dict = None

    def _load_general_input_yamls(self):
        """ Loads all general input yamls into the postprocessor object """
        # Load project file:
        with open(os.path.join(self.data_in_path, self.project_file), 'r', encoding='utf-8') as f:
            self.project = yaml.load(f, Loader=UniqueKeyLoader)
        # Load config:
        with open(os.path.join(self.data_in_path,  self.project['config']), 'r', encoding='utf-8') as f:
            self.config = yaml.load(f, Loader=UniqueKeyLoader)
        # Load technologies:
        with open(os.path.join(self.data_in_path,  self.project['technologies']), 'r', encoding='utf-8') as f:
            self.technologies = yaml.load(f, Loader=UniqueKeyLoader)['technologies']
        # Load timeseries:
        with open(os.path.join(self.data_in_path,  self.project['timeseries']), 'r', encoding='utf-8') as f:
            self.timeseries = yaml.load(f, Loader=UniqueKeyLoader)
        # Load general_param:
        with open(os.path.join(self.data_in_path,  self.project['general_param']), 'r', encoding='utf-8') as f:
            self.general_param = yaml.load(f, Loader=UniqueKeyLoader)

    def build_output_dict(self, output_path:str=None) -> dict:
        """ Creates a dict containing all variables and parameters as dataframes

        Args:
            output_path (str, optional):If a path is given, the output_dict will
            be saved there. Defaults to None.
        """
        # Initiate empty dict:
        output_dict = {}

        # Loop over all vars and add content to dataframe:
        for variable in list(self.model.component_objects(Var, descend_into=True)):
            output_dict[variable.name] = self.get_dataframe_from_result_var(variable)

        # Loop over all params and add content to dataframe:
        for parameter in list(self.model.component_objects(Param, descend_into=True)):
            output_dict[parameter.name] = self.get_dataframe_from_result_param(parameter)

        # Add custom entries:
        output_dict = self._add_custom_entries(output_dict)

        if output_path is not None:
            with open(f"{output_path}.pkl", 'wb') as f:
                pickle.dump(output_dict, f)
        self.output_dict = output_dict
        return output_dict

    def _add_custom_entries(self, output_dict):
        """ Adds processed entries to the output_dict:
        * total_lost_load
        """
        # If the solver did not terminate succesfully, return the output_dict without changes:
        if str(self.result['Solver'][0]['Termination condition']) not in {'maxTimeLimit','optimal'}:
            return output_dict

        # calculate lost load (sum up over all products:)
        products = list(self.model.products)
        scenarios = list(self.model.scenarios)
        output_dict['Total_lost_load_kWh'] = {
            scenario: sum(sum(
                output_dict['Products_lost_load'][product,:, scenario].values * output_dict['time_slice_weight'].values
                        ) for product in products)
            for scenario in scenarios
        }
        return output_dict

    def get_dataframe_from_result_var(self, model_instance_variable, unstack: list = None):
        """ Returns a dataframe with the results from the optimization model."""

        variable = {
            index: model_instance_variable[index].value
            for index in model_instance_variable
        }
        # Create pandas Series from dict
        variable = pd.Series(variable)
        if unstack:
            variable = variable.unstack(unstack)

        return variable

    def get_dataframe_from_result_param(self, model_instance_parameter, unstack: list = None):
        """ Returns a dataframe with the results from the optimization model."""

        parameter = {
            index: model_instance_parameter[index]
            if isinstance(model_instance_parameter[index], (float, int, np.int32, np.int64))
            else model_instance_parameter[index]()
            for index in model_instance_parameter
        }
        # Create pandas Series from dict
        parameter = pd.Series(parameter)
        if unstack:
            parameter = parameter.unstack(unstack)

        return parameter

    def plot_results(self, scenario_name=None, export_path=None, show_plot=False):
        """ Creates visualization object and plots the results"""
        if self.output_dict is None:
            self.build_output_dict()

        visualization = Visualization(self.output_dict, self.model)
        if export_path is None:
            export_path = os.path.join(get_data_out(self.data_in_path, self.project_file), 'plot')

        visualization.plot_results(
            scenario_name = scenario_name,
            export_path   = export_path,
            show_plot     = show_plot)

        return visualization

    def export_short_results(self, export_path:str):
        """ Exports TAC, OPEX and CAPEX to a .yaml file

        Args:
            export_path (str): destination of the .yaml file
        """
        if self.output_dict is None:
            self.build_output_dict()

        termination_condition = str(self.result['Solver'][0]['Termination condition'])

        if termination_condition in {'maxTimeLimit', 'optimal'}:
            # Calculate lost load (sum up over all products:)
            products = list(self.model.products)
            scenarios = list(self.model.scenarios)
            lost_load_kWh = {
                scenario: float(sum(sum(
                    self.output_dict['Products_lost_load'][product,:, scenario].values * self.output_dict['time_slice_weight'].values
                            )for product in products))
                for scenario in scenarios
            }
            export_dict = {
                'TAC': float(self.output_dict['TAC'][None]),
                'OPEX': {scenario: float(self.output_dict['OPEX'][scenario])
                        for scenario in self.output_dict['OPEX'].index},
                'CAPEX': {scenario: float(self.output_dict['CAPEX'][scenario])
                        for scenario in self.output_dict['CAPEX'].index},
                'lost_load_kWh': lost_load_kWh,
                'overcapacity': float(self.output_dict['Overcapacity'].values[0]),
                'termination_condition' : termination_condition,
                'upper_bound' : self.result['Problem'][0]['upper_bound'],
                'lower_bound' : self.result['Problem'][0]['lower_bound'],
                'wall_time' : self.result['Solver'][0]['wall_time'],
                'message' : self.result['Solver'][0]['message']
            }
        else:
            export_dict = {
                'termination_condition' : termination_condition,
                'upper_bound' : self.result['Problem'][0]['upper_bound'],
                'lower_bound' : self.result['Problem'][0]['lower_bound'],
                'wall_time' : self.result['Solver'][0]['wall_time'],
                'message' : self.result['Solver'][0]['message']
            }

        with open(f"{export_path}.yaml", 'w', encoding='utf-8') as f:
            yaml.dump(export_dict, f)

    def export_capacities(self, export_path:str):
        """ Exports a dict containing the values of all build capacitities
        of storage and production processes

        Args:
            export_path (str): path of the exported .yaml file (without file extension)
        """

        if self.output_dict is None:
            self.build_output_dict()

        termination_condition = str(self.result['Solver'][0]['Termination condition'])

        export_dict = {
            'termination_condition': termination_condition
        }
        # if an optimal solution was foundm save the nominal capacities
        if termination_condition in {'maxTimeLimit', 'optimal'}:
            # loop over all cluster categories:
            export_dict |= {
                key: float(value)
                for key, value in self.output_dict['Production_nominal_capacity'].items()
            }
            export_dict |= {
                key: float(value)
                for key, value in self.output_dict['Storage_nominal_capacity'].items()
            }

        with open(f"{export_path}.yaml", 'w', encoding='utf-8') as f:
            yaml.dump(export_dict, f)

    def export_output_dict(self, export_path:str):
        """ Exports the full output_dict as a pickle file.

        Args:
            export_path (str): path of the exported .pkl file (without file extension)
        """
        if self.output_dict is None:
            self.build_output_dict()

        # save dict as pickle file:
        with open(f"{export_path}.pkl", 'wb') as f:
            pickle.dump(self.output_dict, f)

class Visualization():
    """ Class for visualizing optimization results using Bokeh."""
    def __init__(self, output_dict, model):
        """
        Args:
            output_dict (dict): dictionary containing all optimization results
            model (pyomo.environ.ConcreteModel): Pyomo model
        """
        self.output_dict = output_dict
        self.model = model

        # Save all build production and storage processes:
        self.production_processes = {
            k for k, v in self.output_dict['Production_nominal_capacity'].items() if v > 0
            }
        self.storage_processes = {
            k for k, v in self.output_dict['Storage_nominal_capacity'].items() if v > 0
            }

        # df which contains data that will be displayed positive:
        self.df_positive = pd.DataFrame()
        # df which contains data that will be displayed negative:
        self.df_negative = pd.DataFrame()

        self.products = self.output_dict['Products_buy'].keys().map(lambda x:x[0]).unique().tolist()

    def get_color_cycle(self):
        """ Returns a color cycle iterator with RWTH colors.

        Returns:
            itertools.cycle: iterator with RWTH colors
        """
        return itertools.cycle([
            set_rwth_color('blue',100),
            set_rwth_color('blue',50),
            set_rwth_color('green',100),
            set_rwth_color('orange',100),
            set_rwth_color('red',100),
            set_rwth_color('magenta',100),
            set_rwth_color('yellow',100),
            set_rwth_color('petrol',100),
            set_rwth_color('cyan',100),
            set_rwth_color('maygreen',100),
            set_rwth_color('bordeaux',100),
            set_rwth_color('purple',100),
            set_rwth_color('lilac',100),
            ])

    def plot_results(self, plots_per_row:int=2, scenario_name:str=None, export_path=None,
                     show_plot=True):
        """ Plots the results of the optimization.

        Args:
            plots_per_row (int, optional): Number of plots per row. Defaults to 2.
            scenario_name (str, optional): Name of the scenario to be plotted. If None,
                the first scenario in output_dict will be used. Defaults to None.
            export_path (str, optional): Path where the html file will be saved. If None,
                the file will be saved in the data_out folder. Defaults to None.
            show_plot (bool, optional): If True, the plot will be shown in a browser window.
        """
        # If no scenario is given, use the first scenario in output_dict:
        if scenario_name is None:
            scenario_name =self.output_dict['pricebuy_scaled'].keys().map(lambda x:x[2]).unique()[0]

        unstack = {
            'Production_prod': [0,1,3],
            'Demand': [0,2],
            'Products_buy': [0,2],
            'Products_sell': [0,2],
            'Storage_power_in':[0,1,3],
            'Storage_power_out': [0,1,3],
            'Storage_stored_energy': [0,2],
            'Products_lost_load': [0, 2]
        }
        # Remove entries from unstack, if the output_dict is empty for that key:
        unstack = {key: value for key, value in unstack.items() if len(self.output_dict[key])>0}

        # Create energy balance plots:
        keys_balance_positive, keys_balance_negative = self._get_energy_balance_data(
            scenario_name=scenario_name,
            unstack=unstack)
        balance_plots = self._get_energy_balance_plots(
            keys_balance_positive,
            keys_balance_negative)
        balance_section = self._create_plots(
            balance_plots, "Energy balances", plots_per_row=plots_per_row
            )

        # Create storage plots:
        keys_storage = self._get_storage_data(
            scenario_name=scenario_name,
            unstack=unstack
        )
        storage_plots = self._get_storage_plots(keys_storage=keys_storage)
        storage_section = self._create_plots(
            storage_plots, "Storage", plots_per_row=plots_per_row
            )

        # Create production table:
        production_table = self._get_production_table(scenario_name)
        production_title = self._get_title("Production Processes")

        # Create storage table:
        storage_table = self._get_storage_table(scenario_name)
        storage_title = self._get_title("Storage Processes")

        # Create cost table:
        cost_table = self._get_cost_table(scenario_name)
        cost_title = self._get_title("Costs")

        # Create demand table:
        demand_table = self._get_demand_table(scenario_name)
        demand_title = self._get_title("Products")

        # Create product buy table:
        pricebuy_table = self._get_pricebuy_table(scenario_name)
        pricebuy_title = self._get_title("Price Buy")

        # Create product sell table:
        pricesell_table = self._get_pricesell_table(scenario_name)
        pricesell_title = self._get_title("Price Sell")

        # Create input timeseries plots:
        timeseries_plots = self._get_timeseries_plots(scenario_name)
        timeseries_section = self._create_plots(
            timeseries_plots, "Timeseries", plots_per_row=plots_per_row+1
            )

        process_row = row(
            column(production_title, production_table),
            column(storage_title,    storage_table)
        )
        # Set layout:
        layout = column(
            *balance_section,
            *storage_section,
            process_row,
            cost_title,
            cost_table,
            demand_title,
            demand_table,
            pricebuy_title,
            pricebuy_table,
            pricesell_title,
            pricesell_table,
            *timeseries_section,
            sizing_mode="stretch_width" )

        if export_path is not None:
            output_file(f"{export_path}.html")
            save(layout)

        if show_plot:
            show(layout)

    def _get_title(self, title:str):
        """ Helper function to create a title Div element."""
        return Div(
            text=f"<div style='text-align: center;font-weight: bold; font-size: 24px'>{title}</div>"
            )

    def _create_plots(self, plot_dict:dict, title_text:str, plots_per_row:int):
        """ Helper function to create plot rows with a title."""

        plot_list = list(plot_dict.values())
        rows_of_plots = [
            row(*plot_list[i:i+plots_per_row]) for i in range(0, len(plot_list), plots_per_row)
            ]
        return [self._get_title(title_text)] + rows_of_plots

    def _add_timesteps(self):
        """ Adds a 'time_steps' column to both positive and negative dataframes."""
        if 'time_steps' not in self.df_negative:
            self.df_negative['time_steps'] = self.df_negative.index.to_list()
        if 'time_steps' not in self.df_positive:
            self.df_positive['time_steps'] = self.df_positive.index.to_list()

    def _get_energy_balance_data(self, scenario_name:str, unstack:dict):
        """ Creates data for energy balance plots.

        Args:
            scenario_name (str): _name of the scenario to be plotted
            unstack (dict): dict defining how to unstack each variable

        Returns:
            keys_balance_positive (dict): dict with keys of positive energy flows
            keys_balance_negative (dict): dict with keys of negative energy flows
        """
        multiplier = {
            'Production_prod': 1,
            'Demand': -1,
            'Products_buy': 1,
            'Products_sell': -1,
            'Storage_power_in': -1,
            'Storage_power_out': 1,
            'Products_lost_load': 1
        }
        # Remove entries from unstack, which are not in unstack:
        multiplier = {key: value for key, value in multiplier.items() if key in unstack}

        unstack = {key: value for key, value in unstack.items() if len(self.output_dict[key])>0}
        keys_balance_positive = {key: [] for key in self.products}
        keys_balance_negative = {key: [] for key in self.products}
        for key_name, multiplier_value in multiplier.items():
            unstacked_df = self.output_dict[key_name].unstack(unstack[key_name])
            for column_name, column_data in unstacked_df.items():
                if column_name[-1] != scenario_name:
                    continue
                name = f'{key_name}_' + '_'.join(column_name[:-1])
                product = column_name[0]
                # Check if column of dataframe only contains zero:
                if (column_data == 0).all():
                    continue

                if (multiplier_value * column_data >= 0-1E-8).all():
                    self.df_positive[name] = multiplier_value * column_data
                    keys_balance_positive[product].append(name)
                elif (multiplier_value * column_data <= 0+1E-8).all():
                    self.df_negative[name] = multiplier_value * column_data
                    keys_balance_negative[product].append(name)
                else:
                    raise ValueError(
                        "Unexpected variables values, some are negative, some are positive")

        self._add_timesteps()
        return keys_balance_positive, keys_balance_negative

    def _get_energy_balance_plots(self, keys_balance_positive:dict, keys_balance_negative:dict):
        """ Creates energy balance plots.
        Args:
            keys_balance_positive (dict): dict with keys of positive energy flows
            keys_balance_negative (dict): dict with keys of negative energy flows

        Returns:
            balance_plots (dict): dict with energy balance plots
        """
        balance_plots = {}
        # Plot energy balances
        for product in self.products:
            colors = self.get_color_cycle()
            # If there are no energy flows for the current product, continue
            if len(keys_balance_positive[product]) + len(keys_balance_positive[product]) == 0:
                continue
            if product not in balance_plots:
                balance_plots[product] = figure(
                    title=f'Energy balance: {product}',
                    x_axis_label='Timestep',
                    y_axis_label=f'{product}/ kW',
                    tools="pan,box_zoom,zoom_in,zoom_out,wheel_zoom,save,reset,crosshair,hover",
                    width=900
                )

            balance_plots[product].vbar_stack(
                keys_balance_positive[product],
                x='time_steps',
                width=0.9,
                color=[next(colors) for _ in keys_balance_positive[product]],
                source=self.df_positive,
                legend_label=list(keys_balance_positive[product]),
            )
            balance_plots[product].vbar_stack(
                keys_balance_negative[product],
                x='time_steps',
                width=0.9,
                color=[next(colors) for _ in keys_balance_negative[product]],
                source=self.df_negative,
                legend_label=list(keys_balance_negative[product]),
            )
            balance_plots[product].legend.click_policy = 'hide'

        return balance_plots

    def _get_storage_data(self, scenario_name:str, unstack:dict):
        """ Creates data for storage plots."""
        # Return empty list, if no storages are build:
        if len(self.output_dict['Storage_power_in']) == 0:
            return []

        keys_storage = {
            key: [] for key, value in self.output_dict['Storage_nominal_capacity'].items()
                if value>0}
        # Add storage in and outflow:
        for key_name in ['Storage_power_in', 'Storage_power_out']:
            unstacked_df = self.output_dict[key_name].unstack(unstack[key_name])
            for column_name, column_data in unstacked_df.items():
                product_name = column_name[0]
                component_name = column_name[1]
                scenario = column_name[-1]

                # Skip, if it is the wrong scenario
                if scenario != scenario_name:
                    continue

                if component_name not in keys_storage:
                    continue

                # Skip, if its not the reference product of the storage
                reference_products = {
                    key[0]
                    for key in list(self.model.constraint_storage_level_rule.keys())
                    if key[1] == component_name
                    }
                if product_name not in reference_products:
                    continue

                name = f'{key_name}_' + '_'.join(column_name[:-1])
                self.df_positive[name] = column_data
                keys_storage[component_name].append(name)

        # Add storaged energy:
        key_name = 'Storage_stored_energy'

        unstacked_df = self.output_dict[key_name].unstack(unstack[key_name])
        for column_name, column_data in unstacked_df.items():
            scenario = column_name[-1]
            component_name = column_name[0]

            # Skip, if it is the wrong scenario
            if scenario != scenario_name:
                continue

            if component_name not in keys_storage:
                continue

            name = f'{key_name}_' + '_'.join(column_name[:-1])
            self.df_positive[name] = column_data
            keys_storage[component_name].append(name)

        return keys_storage

    def _get_storage_plots(self, keys_storage):
        """ Creates storage plots."""
        storage_plots = {}
        # Plot energy balances
        for storage in keys_storage:
            colors = self.get_color_cycle()
            if storage not in storage_plots:
                storage_plots[storage] = figure(
                    title=f'Storage: {storage}',
                    x_axis_label='Timestep',
                    y_axis_label='storage level / kWh or power / kW',
                    tools="pan,box_zoom,zoom_in,zoom_out,wheel_zoom,save,reset,crosshair,hover",
                    width=900
                )
            # Loop through each key and add a line glyph for each one
            for key in keys_storage[storage]:
                storage_plots[storage].line(
                    x='time_steps',
                    y=key,
                    line_width=2,
                    color=next(colors),
                    source=self.df_positive,
                    legend_label=key,
                )
            storage_plots[storage].legend.click_policy = 'hide'

        return storage_plots

    def _get_production_table(self, scenario:str):
        """ Creates a production process summary table."""
        production_processes = list(self.production_processes)
        prod_invest = [
            f"{self.output_dict['production_investment_cost'][process][scenario] * self.output_dict['Production_nominal_capacity'][process]:.3e}"
            for process in production_processes
        ]

        prod_capacity = [
            f"{self.output_dict['Production_nominal_capacity'][process]:.3e}"
            for process in production_processes
        ]

        prod_maint = [
            f"{self.output_dict['production_maintenance_cost'][process][scenario]/100 * self.output_dict['Production_nominal_capacity'][process]:.3e}"
            for process in production_processes
        ]

        # Get operating hours:
        prod_operation_hours = []
        for process in production_processes:
            hours_producing = self.output_dict['Production_load'].loc[process,:,scenario].values !=0

            prod_operation_hours.append(
                sum(np.where(hours_producing, 1, 0) * self.output_dict['time_slice_weight'].values)
                )

        # Get capacity factor:
        total_hours = self.output_dict['time_slice_weight'].sum()
        prod_capacity_factor = []
        for process in production_processes:
            production_load = self.output_dict['Production_load'].loc[process,:,scenario].values
            weighted_load = sum(
                production_load * self.output_dict['time_slice_weight'].values
            )
            full_load = total_hours * self.output_dict['Production_nominal_capacity'][process]
            prod_capacity_factor.append(f"{weighted_load/full_load*100:.2f}")

        # Get availabilities:
        prod_avail_list = []
        for process in production_processes:
            prod_avail = self.output_dict['production_availability'].loc[process,:,scenario].values

            mean_avail = sum(prod_avail * self.output_dict['time_slice_weight'].values) /total_hours

            # Build string: min | mean | max:
            prod_avail_list.append(
                f"{prod_avail.min():.2f} | {mean_avail:.2f} | {prod_avail.max():.2f}"
            )

        data = {
            'process'          : production_processes,
            'nominal_capacity' : prod_capacity,
            'invest_cost'      : prod_invest,
            'maint_cost'       : prod_maint,
            'operating_hours'  : prod_operation_hours,
            'capacity_factor'  : prod_capacity_factor,
            'availability'     : prod_avail_list
        }
        source = ColumnDataSource(data)

        columns = [
            TableColumn(field="process",         title="Process"),
            TableColumn(field="nominal_capacity",title="Nominal Capacity [kW]"),
            TableColumn(field="invest_cost",     title="Invest cost [€]"),
            TableColumn(field="maint_cost",      title="Maintenance cost [€]"),
            TableColumn(field="operating_hours", title="Operating hours [h]"),
            TableColumn(field="capacity_factor", title="Capacity factor [%]"),
            TableColumn(field="availability",    title="Availability (min | mean | max)",width=400),
        ]

        return DataTable(
            source  = source,
            columns = columns,
            height  = 30 * (1 + len(production_processes)),
            width   = 1000
        )

    def _get_storage_table(self, scenario:str):
        """ Creates a storage process summary table."""
        storage_processes = list(self.storage_processes)

        stor_invest = [
            f"{self.output_dict['storage_investment_cost'][component][scenario] * self.output_dict['Storage_nominal_capacity'][component]:.3e}"
            for component in storage_processes
        ]

        stor_maint = [
            f"{self.output_dict['storage_maintenance_cost'][component][scenario] / 100 * self.output_dict['Storage_nominal_capacity'][component]:.3e}"
            for component in storage_processes
        ]

        stor_capacity = [
            f"{self.output_dict['Storage_nominal_capacity'][component]:.3e}"
            for component in storage_processes
        ]

        # Get the reference product:
        stor_product = []
        for process in storage_processes:
            reference_products = {
                key[0]
                for key in list(self.model.constraint_storage_level_rule.keys())
                if key[1] == process
            }

            if len(reference_products) != 1:
                warnings.warn(
                    f"Something went wrong for storage process '{process}' " +
                    f"as the number of reference products '{reference_products}' " +
                    "is not equal to one"
                )

            stor_product.append(list(reference_products)[0])

        data = {
            'process'          : storage_processes,
            'product'          : stor_product,
            'nominal_capacity' : stor_capacity,
            'invest_cost'      : stor_invest,
            'maintenance_cost' : stor_maint,
        }
        source = ColumnDataSource(data)

        columns = [
            TableColumn(field="process",          title="Process"),
            TableColumn(field="product",          title="Product"),
            TableColumn(field="nominal_capacity", title="Nominal Capacity [kWh]"),
            TableColumn(field="invest_cost",      title="Invest cost [€]"),
            TableColumn(field="maintenance_cost", title="Maintenance cost [€]")
        ]

        return DataTable(
            source  = source,
            columns = columns,
            height  = 30 * (1 + len(storage_processes)),
            width   = 800
        )


def sum_up_multiple_results_to_df(esd_names: list, df_in:pd.DataFrame, result_file_location:str,
                                  export_path:str=None):
    """ The results of multiple scenarios and energy systems are summed up to a dataframe.

    Args:
        esd_names (list): list containing the names of the energy systems, e.g. ['ES-B', 'ES-HP']
        df_in (pd.DataFrame): contains all information about the scenarios and uncertain parameters
        result_file_location (str): path to the folder containing the result yaml files
        export_path (str, optional): path to the export file. Defaults to None.
            If None, the dataframe is not exported.

    Returns:
        pd.DataFrame: dataframe containing the results of all scenarios and energy systems
    """
    # Initialize the dataframe with multiindex columns
    df_out = df_in.copy()

    # Loop over all energy systems:
    for i, esd in enumerate(esd_names):
        print(f"Energy System {esd}, {i+1}/{len(esd_names)}")
        tac = []
        opex = []
        capex = []
        termination = []

        # Loop over all scenarios
        for _, my_row in df_in.iterrows():
            scenario_name = my_row['scenarios']
            # Load the result yaml file
            yaml_name = f'{esd}_{scenario_name}_KPIs.yaml'
            with open(os.path.join(result_file_location, yaml_name), 'r', encoding='utf-8') as f:
                result_dict = yaml.load(f, Loader=UniqueKeyLoader)
            termination.append(result_dict['termination_condition'])
            if result_dict['termination_condition'] == 'optimal':
                tac.append(result_dict['TAC'])
                opex.append(result_dict['OPEX'][scenario_name])
                capex.append(result_dict['CAPEX'][scenario_name])
            else:
                print("Info: nonoptimal entry")
                tac.append(None)
                opex.append(None)
                capex.append(None)

        df_out[f'TAC_{esd}'] = tac
        df_out[f'OPEX_{esd}'] = opex
        df_out[f'CAPEX_{esd}'] = capex
        df_out[f'termination_condition_{esd}'] = termination

    # Export the dataframe
    if export_path is not None:
        df_out.to_csv(add_file_extension(export_path,'csv'), index=False)

    return df_out

def calculate_regret(df_in:pd.DataFrame, esd_names:list, target_variables:list,
                     export_path:str=None) -> pd.DataFrame:
    """ Calculates the regret for the given target variables and energy system designs.

    Args:
        df_in (pd.DataFrame): dataframe containing the results for all energy system designs
        esd_names (list): names of the energy system designs, e.g. ['ES-B', 'ES-HP']
        target_variables (list): target variables for which the regret should be calculated
        export_path (str, optional): path to the export file. Defaults to None.

    Returns:
        pd.DataFrame: dataframe containing the regret values for all target variables
    """
    # Copy the input dataframe
    df_out = df_in.copy()

    # Check that all target variables are in the dataframe
    regret_columns = [f"{var}_{esd}"for var, esd in itertools.product(target_variables, esd_names)]
    assert all(column_name in df_out.columns for column_name in regret_columns), (
        'Not all comnbinations of target variables and ESDs are in the dataframe')

    # Loop over all target_variables:
    for target_variable in target_variables:
        target_columns = [f"{target_variable}_{esd}" for esd in esd_names]
        df_target = df_out[target_columns]
        # Get row-wise minimum:
        df_regret = df_target.subtract(df_target.min(axis=1), axis=0)

        # Add 'regret_' to the column names
        df_regret.columns = [f"regret_{column}" for column in df_regret.columns]

        # Add the regret to the dataframe
        df_out = pd.concat([df_out, df_regret], axis=1)

    # Export the dataframe
    if export_path is not None:
        df_out.to_csv(add_file_extension(export_path,'csv'), index=False)

    return df_out

def export_esd_to_yaml(data_path_in:str, project_file:str, output_dict:pd.DataFrame, esd_name:str,
                       add_to_input_designs:bool=False, data_path_out:str=None):
    """ Exports an energy system design in .yaml format

    Args:
        data_path_in (str): path to the input file (where the project file lies)
        project_file (str): name of the .yaml file in data_in_path containing the input information
            e.g., project.yaml
        output_dict (pd.DataFrame): output dict generated by PostProcessor 
        esd_name (str): name of the energy system
        add_to_input_designs (bool, optional): If the design should be added to the input.
            Defaults to False.
        data_path_out (str, optional): export path. Defaults to None.

    Returns:
        dict: energy system design in dict format (equal to .yaml strucutre)
    """
    # Load project file:
    with open(os.path.join(data_path_in, project_file), 'r', encoding='utf-8') as f:
        project = yaml.load(f, Loader=UniqueKeyLoader)
    # Load superstructure:
    with open(os.path.join(data_path_in, project['superstructures']), 'r', encoding='utf-8') as f:
        superstructure_name = get_config_file(data_path_in, project_file)['superstructure_name']
        superstructure = yaml.load(
            f, Loader=UniqueKeyLoader)['superstructures'][superstructure_name]

    # Generate list containing all installed production processes:
    production_processes = [
        key for key, value in output_dict['Production_nominal_capacity'].items()
        if value > 0
    ]
    storage_processes = [
        key for key, value in output_dict['Storage_nominal_capacity'].items()
        if value > 0
    ]

    # Check that all processes are listed in the superstructure:
    assert all(process in superstructure for process in production_processes + storage_processes), (
        "output_dict does not seem to belong to the given superstructure")
    # Check that a process is either a storage process or a production process:
    assert len(production_processes) + len(storage_processes) == len(
        set(production_processes + storage_processes))
    # Initialize empty dict:
    esd_dict = {}

    for process in production_processes + storage_processes:
        # Add the name of the process type, e.g. CC_medium
        esd_dict[process] = {'type': superstructure[process]['type']}

        # Add the nominal capacity
        if process in production_processes:
            esd_dict[process]['nominal_capacity_kW'] = output_dict[
                'Production_nominal_capacity'][process]
        else:
            esd_dict[process]['nominal_capacity_kWh'] = float(
                output_dict['Storage_nominal_capacity'][process])

        # Add values from the superstructure, which havnt been added so far
        esd_dict[process].update({
            key: value for key, value in superstructure[process].items()
            if key not in esd_dict[process]
        })

        # Convert all numpy.arrays to floats:
        esd_dict[process].update({
            key: float(value) for key, value in esd_dict[process].items()
            if isinstance(value, np.float64)
        })

    # If wanted, the design in added to the input design .yaml file
    if add_to_input_designs:
        def get_unused_name(target_keys:list, key:str, i:int=0):
            """ helper function which checks, if the given key already exists in
            'target_keys'.
            if i>0, _i is added at the end of the string. The method is repeated 
            recoursively.

            Args:
                target_keys (list): list of the already existing keys in the target dict
                key (str): the which is intended to be added
                i (int, optional): inticates, which numbers already have been tried

            Returns:
                str: a key which is not already a key in the target_keys
            """
            tried_key = key if i == 0 else f"{key}_{i}"

            if tried_key in target_keys:
                tried_key = get_unused_name(target_keys, key, i+1)
                if i == 0:
                    warnings.warn(
                        f"{key} already exists in target_keys. Choosing {tried_key} instead.")
            return tried_key

        # Load design:
        with open(os.path.join(data_path_in, project['designs']), 'r', encoding='utf-8') as file:
            designs = yaml.load(file, Loader=UniqueKeyLoader)

        esd_name = get_unused_name(designs.keys(), esd_name)

        # Add new esd to designs:
        designs['designs'][esd_name] = esd_dict

        # Save changes input designs:
        with open(os.path.join(data_path_in, project['designs']), 'w', encoding='utf-8') as f:
            yaml.safe_dump(designs, f)

    # Export esd_dict:
    if data_path_out is not None:
         # Add new layer to the esd_dict, to export it:
        dict_out = {'designs':{esd_name:esd_dict}}

        with open(f"{data_path_out}.yaml", 'w', encoding='utf-8') as f:
            yaml.safe_dump(dict_out, f) 
    return esd_dict

def sum_up_capacity_results_to_df(data_path_in: str, project_file:str, df_in:pd.DataFrame,
                                  result_file_location:str, export_path:str=None):
    """ The results of multiple scenarios and energy systems are summed up to a dataframe. The
    capacities of the components are summed up for each cluster category. The cluster categories are
    defined in the clustering.yaml file. Intended use is after deterministic DESIGN optimizations
    for several scenarios. Method is not intended to be used after OPERATIONAL optimizations for
    several scenarios and energy system designs.

    Args:
        data_path_in (str): path to the folder containing the project file, superstructures.yaml
            and clustering.yaml
        project_file (str): name of the .yaml file in data_in_path containing the input information
            (e.g. project.yaml)
        df_in (pd.DataFrame): contains all information about the scenarios and uncertain parameters
        result_file_location (str): path to the folder containing the result yaml files
        export_path (str, optional): path to the export file. Defaults to None.

    Returns:
        pd.DataFrame: dataframe containing the results of all scenarios and energy systems
    """
    with open(os.path.join(data_path_in, project_file), 'rb') as file:
        project = yaml.load(file, Loader=UniqueKeyLoader)
    with open(os.path.join(data_path_in, project['superstructures']), 'rb') as file:
        superstructure_name = get_config_file(data_path_in, project_file)['superstructure_name']
        superstructure = yaml.load(
            file, Loader=UniqueKeyLoader)['superstructures'][superstructure_name]
    with open(os.path.join(data_path_in, project['technology_categories']), 'rb') as file:
        technology_categories = yaml.load(file, Loader=UniqueKeyLoader)['technology_categories']

    for key in technology_categories:
        technology_categories[key]['components'] = [
            component for component in superstructure
            if superstructure[component]['type'] in technology_categories[key]['component_types']
        ]
    # Create empty dict with technology_categories as keys:
    aux_dict = {cluster_category: [] for cluster_category in technology_categories}
    # Add empty lists for TAC, CAPEX and OPEX:
    aux_dict.update({key: [] for key in ['TAC', 'CAPEX', 'OPEX']})

    df_out = df_in.copy()
    for _, my_row in df_out.iterrows():
        scenario_name = my_row['scenarios']

        # Load the capacities file:
        yaml_name = f'{scenario_name}_capacities.yaml'
        with open(os.path.join(result_file_location, yaml_name), 'r', encoding='utf-8') as f:
            capacity_dict = yaml.load(f, Loader=UniqueKeyLoader)

        for cluster_category, cluster_dict in technology_categories.items():
            aux_dict[cluster_category].append(sum(
                capacity_dict[component] for component in cluster_dict['components']
            ))

        # Load the results file with TAC, CAPEX and OPEX:
        yaml_name = f'{scenario_name}_KPIs.yaml'
        with open(os.path.join(result_file_location, yaml_name), 'r', encoding='utf-8') as f:
            kpi_dict = yaml.load(f, Loader=UniqueKeyLoader)

        # Add TAC:
        aux_dict['TAC'].append(kpi_dict['TAC'])
        # Add CAPEX and OPEX:
        for key in ['CAPEX', 'OPEX']:
            aux_dict[key].append(kpi_dict[key][scenario_name])

    # Add the new columns to the dataframe:
    for key, value in aux_dict.items():
        df_out[key] = value

    # Export the dataframe
    if export_path is not None:
        df_out.to_csv(add_file_extension(export_path,'csv'), index=False)

    return df_out


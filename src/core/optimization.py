        model.constraint_storage_capacity_ratio_in = Constraint(
            model.products, model.processes_storage, model.t, model.scenarios,
            rule = constraint_storage_capacity_ratio_in
        )

        def constraint_storage_capacity_ratio_out(model, product, process, t, scenario):
            """ Constraint #22 in https://doi.org/10.1016/j.compchemeng.2023.108176 """
            return(
                model.Storage_power_out[product, process, t, scenario]
                <=
                model.storage_capacity_ratio[product, process, scenario] * model.Storage_nominal_capacity[process]
            )
        model.constraint_storage_capacity_ratio_out = Constraint(
            model.products, model.processes_storage, model.t, model.scenarios,
            rule = constraint_storage_capacity_ratio_out
        )

        def constraint_storage_potential_capacity_rule(model, process):
            """ Constraint #15 in https://doi.org/10.1016/j.compchemeng.2023.108176 """
            return(
                model.Storage_nominal_capacity[process]
                <= 
                model.storage_potential_capacity[process] * model.Storage_binary_exists[process]
            )
        model.constraint_storage_potential_capacity_rule = Constraint(
            model.processes_storage,
            rule = constraint_storage_potential_capacity_rule
        )

        def constraint_storage_minimal_capacity_rule(model, process):
            """ Constraint #16 in https://doi.org/10.1016/j.compchemeng.2023.108176 """
            return(
                model.Storage_nominal_capacity[process]
                >= 
                model.storage_minimal_capacity[process] * model.Storage_binary_exists[process]
            )
        model.constraint_storage_minimal_capacity_rule = Constraint(
            model.processes_storage,
            rule = constraint_storage_minimal_capacity_rule
        )

        def constraint_storage_deposit_decision_rule(model, product, process, t, scenario):
            """ Constraint #24 in https://doi.org/10.1016/j.compchemeng.2023.108176 """
            return(
                model.Storage_power_in[product, process, t, scenario]
                <=
                model.storage_capacity_ratio[product, process, scenario] * model.storage_potential_capacity[process]
                * model.Storage_binary_in[process, t, scenario]
            )
        model.constraint_storage_deposit_decision_rule = Constraint(
            model.products, model.processes_storage, model.t, model.scenarios,
            rule = constraint_storage_deposit_decision_rule
        )

        def constraint_storage_withdrawal_decision_rule(model, product, process, t, scenario):
            """ Constraint #25 in https://doi.org/10.1016/j.compchemeng.2023.108176 """
            return(
                model.Storage_power_out[product, process, t, scenario]
                <=
                model.storage_capacity_ratio[product, process, scenario] * model.storage_potential_capacity[process]
                *  model.Storage_binary_out[process, t, scenario]
            )
        model.constraint_storage_withdrawal_decision_rule = Constraint(
            model.products, model.processes_storage, model.t, model.scenarios,
            rule = constraint_storage_withdrawal_decision_rule
        )

        def constraint_storage_restrict_storing_per_timeslice_rule(model, process, t, scenario):
            """ Constraint #23 in https://doi.org/10.1016/j.compchemeng.2023.108176 """
            return(
                model.Storage_binary_in[process, t, scenario]
                + model.Storage_binary_out[process, t, scenario]
                <= 1
            )
        model.constraint_storage_restrict_storing_per_timeslice_rule = Constraint(
            model.processes_storage, model.t, model.scenarios,
            rule = constraint_storage_restrict_storing_per_timeslice_rule
        )

        def constraint_storage_level_rule(model, product, process, t, scenario):
            """ Constraint #19 in https://doi.org/10.1016/j.compchemeng.2023.108176 """
            # If product is not the reference product, skip Constraint, since this constriant
            # is only indented for the reference product:
            if input_dict['storage_reference'][process] != product:
                return Constraint.Skip

            return(
                # sum of the current storage level, the deposits and withdrawals
                # current storage level:
                (model.Storage_stored_energy[process, t, scenario]*(1-model.storage_loss_percent[process, scenario]/100)**model.time_slice_duration[t]
                # deposits: multiplication of the duration of the time slice with the deposits from the storage
                + (model.time_slice_duration[t] * model.Storage_power_in[product, process, t, scenario] * model.storage_efficiency_deposit[process])
                # withdrawals: multiplication of the duration of the time slice with the withdrawals from the storage
                - (model.time_slice_duration[t] * model.Storage_power_out[product, process, t, scenario] / model.storage_efficiency_withdrawal[process])
                )
                # the sum above equal the storage level of the next time slice
                ==
                model.Storage_stored_energy[process, model.next_time_slice[t], scenario]
            )
        model.constraint_storage_level_rule = Constraint(
            model.products, model.processes_storage, model.t, model.scenarios,
            rule = constraint_storage_level_rule
        )

        #-------------- Objective Function: ------------------------------------------

        # max overcapacity: only for max_overcapacity:
        if self.optimization_type == 'max_overcapacity':
            def rule_objective_constraint(model):
                return model.Overcapacity
            model.obj = Objective(rule=rule_objective_constraint, sense=maximize)

        # min TAC: for all optimization_types except for max_overcapacity:
        else:
            def rule_objective_constraint(model):
                return model.TAC
            model.obj = Objective(rule=rule_objective_constraint)

        return model

""" Core optimization classes and methods. """
import os
import time
import warnings
import yaml
import pandas as pd
from pyomo.environ import (Set, Constraint, Param, Var, SolverFactory, ConcreteModel,
                           NonNegativeReals, Reals, Binary, Objective, maximize)
from pyomo.common.errors import ApplicationError
from core.helpers import UniqueKeyLoader, get_config_file

class Optimization:
    """ Base class for optimizations."""
    def __init__(self, data_in_path, project_file:str, input_dict:dict):
        """
        Args:
            data_in_path (str): path to the input data (containing the project file)
            input_dict (dict): scaled input_dict generated by preprocessing.ScaledInputDictGenerator
            project_file (str): name of the .yaml file in data_in_path containing the
                input information
        """
        self.data_in_path = data_in_path
        self.input_dict = input_dict
        self.project_file = project_file

        self.load_general_input_yamls()
        self.optimization_type = self._get_optimization_type()

    def _get_optimization_type(self) -> str:
        """ Determines the optimization type based on the input_dict.

        Returns:
            str: The optimization type, one of: 'stochastic_design', 'deterministic_operation',
                    'deterministic_design', 'max_overcapacity', 'feasible_hull', 'near_optimal'.
        """
        # if more than one scenario is used, it is a stochastic optimization:
        stochastic_optimization = len(self.input_dict['scenarios']) > 1

        objective = self.input_dict['objective']

        # raise error, if a stochastic operational optimization is used
        if stochastic_optimization and objective in {
            'operation', 'max_overcapacity', 'feasible_hull'}:
            raise ValueError(
                "Operational Optimization is only intended to work with a single scenario.")
        if stochastic_optimization and objective == 'design':
            return 'stochastic_design'
        if not stochastic_optimization and objective == 'operation':
            return 'deterministic_operation'
        if not stochastic_optimization and objective == 'design':
            return 'deterministic_design'
        if not stochastic_optimization and objective == 'max_overcapacity':
            return 'max_overcapacity'
        if not stochastic_optimization and objective == 'feasible_hull':
            if self.config['model_formulation'] != 'LP':
                raise ValueError(
                    "'feasible_hull' exploration is intended only for 'LP' formulations. "+
                    f"Got '{self.config['model_formulation']}' instead.")
            return 'feasible_hull'
        if not stochastic_optimization and objective == 'near_optimal':
            if self.config['model_formulation'] != 'LP':
                raise ValueError(
                    "'near_optimal' exploration is intended only for 'LP' formulations. "+
                    f"Got '{self.config['model_formulation']}' instead.")
            return 'near_optimal'

        raise ValueError(f"Invalid optimization objective: {objective}")

    def load_general_input_yamls(self):
        """
        Loads the general input yamls from the data_in_path and stores them
        in the class attributes.
        """
        # load project file:
        with open(os.path.join(self.data_in_path, self.project_file), 'r', encoding='utf-8') as f:
            self.project = yaml.load(f, Loader=UniqueKeyLoader)

        # read config file:
        with open(os.path.join(self.data_in_path,  self.project['config']), 'r', encoding='utf-8') as f:
            self.config = yaml.load(f, Loader=UniqueKeyLoader)

    def solve_model(self, model, mipgap = None, timelimit=None, tee=True,
                    symbolic_solver_labels=False, solve_with_retries=True):
        """ solves the given model with the given remaining gap to optimality (mipgap)

        Args:
            model (pyomo.ConcreteModel): The model to solve.
            mipgap (float, optional): The maximum allowed gap to optimality. Defaults to None.
            timelimit (int, optional): The maximum time in seconds to solve the model.
                Defaults to None.
            tee (bool, optional): Whether to print solver output to the console. Defaults to True.
            symbolic_solver_labels (bool, optional): Whether to use symbolic solver labels.
                Defaults to False.
            solve_with_retries (bool, optional): Whether to retry solving the model in case of
                license issues. Defaults to True.

        Returns:
            pyomo.SolverResults: The results of the solver after successful execution.
        """
        if tee:
            print(f"Solving {self.model_formulation} model...")

        # To enforve the use of gurobi11 or newer, gurobi9 is removed from PATH 
        if 'PATH' in os.environ:
            os.environ['PATH'] = os.pathsep.join(
                [p for p in os.environ['PATH'].split(os.pathsep) if 'gurobi9' not in p]
            )

        solver = SolverFactory(
            'gurobi',
            options=self.config['optimization'][self.optimization_type]['solver_options'])

        if 'custom_logFile' in self.config:
            custom_logfile = self.custom_logFile['optimization'][self.optimization_type]['custom_logFile']
            file_path = os.path.join(
                os.getcwd(),
                pd.to_datetime('today', format='%Y-%m-%d_%H-%M-%S').strftime('%Y-%m-%d_%H-%M-%S') + '_' + custom_logfile)
            # make file:
            if not os.path.exists(file_path):
                open(file_path, 'w', encoding='utf-8').close()
            solver.options["LogFile"] = file_path

        # if no mipgap is given, the value from config is taken:
        if mipgap is None:
            mipgap = self.config['optimization'][self.optimization_type]['MIP_gap']

        solver.options["mipgap"] = mipgap
        if timelimit is not None:
            solver.options["timelimit"] = timelimit

        if solve_with_retries:
            return self.solve_with_retries(
                solver, model, tee=tee, symbolic_solver_labels=symbolic_solver_labels)
        # else:
        return solver.solve(model, tee=tee, symbolic_solver_labels=symbolic_solver_labels)

    def solve_with_retries(
            self, solver, model, tee, symbolic_solver_labels, max_retries=5, delay=10):
        """ The method solves the model with the given solver and retries in case of license issues.

        Args:
            solver (pyomo.SolverFactory): The solver to use for solving the model.
            model (pyomo.ConcreteModel): The model to solve.
            tee (bool): Whether to print solver output to the console.
            symbolic_solver_labels (bool): Whether to use symbolic solver labels.
            max_retries (int, optional): Maximum number of retries in case of license issues.
                Defaults to 5.
            delay (int, optional): Initial delay in seconds before retrying. Defaults to 10.

        Returns:
            pyomo.SolverResults: The results of the solver after successful execution.
        """
        for attempt in range(max_retries):
            try:
                result = solver.solve(model, tee=tee, symbolic_solver_labels=symbolic_solver_labels)
                return result  # Success

            except ApplicationError as e:
                # Only retry for license-related failures
                if "Failed to connect to token server" in str(e):
                    print(
                        f"[Retry {attempt+1}/{max_retries}] License server unavailable. " +
                        f"Retrying in {delay:.1f}s...")
                    time.sleep(delay)
                else:
                    raise  # Other errors should not be retried

     # If all retries fail, raise
        raise RuntimeError(f"Gurobi failed after {max_retries} attempts due to license issues.")

class Optimization_LP(Optimization):
    """
    Child of Optimization() for LPs.
    """
    def __init__(self, data_in_path, project_file:str, input_dict:dict):
        """
        Args:
            data_in_path (str): path to the input data (containing the project file)
            input_dict (dict): scaled input_dict generated by preprocessing.ScaledInputDictGenerator
            project_file (str): name of the .yaml file in data_in_path containing the
                input information (e.g. project.yaml)
        """
        super().__init__(data_in_path, project_file, input_dict)

        self.model_formulation = 'LP'
        # Warn, if another model_formulation than 'LP' is given in config.yaml:
        model_formulation = get_config_file(data_in_path, project_file)['model_formulation']
        if model_formulation != 'LP':
            warnings.warn(
                f"Unexpected model_formulation for Optimiation_LP: '{model_formulation}' " +
                "instead of 'LP'")

    def generate_model(self) -> ConcreteModel:
        """ Generates the pyomo model for the given input data.

        Returns:
            pyomo.ConcreteModel: The generated model.
        """
        print(f"Generating LP model... ({self.optimization_type})")
        input_dict = self.input_dict
        model = ConcreteModel()

        #-------------- Define Sets: -------------------------------------------------
        model.t                    = Set(initialize=input_dict['time_slices'], doc='time slices')
        model.processes_production = Set(initialize=input_dict['processes_production'], doc='set of production processes')
        model.processes_avail_interpolation = Set(initialize=input_dict['processes_availability_interpolation'],doc='processes, where the availability can be interpolated.')
        model.processes_storage    = Set(initialize=input_dict['processes_storage'], doc='set of storage processes')
        model.products             = Set(initialize=input_dict['products'], doc='set of products')
        model.scenarios            = Set(initialize=input_dict['scenarios'], doc='set of scenarios')

        # Search directions:
        model.products_demand_nonprop_scaling = Set(
            initialize = input_dict['products_demand_nonprop_scaling'],
            doc        = 'set of products, where mean and peak do not scale proportionally for the demand timeseries scaling.'
        )

        # Create a set of all processes
        if self.optimization_type == 'near_optimal':
            model.processes = Set(
                initialize=(
                    input_dict['processes_production'] +
                    input_dict['processes_storage']
                ), doc='set of all processes (production and storage)'
        )

        if self.optimization_type == 'feasible_hull':
            model.production_affect_feas  = Set(initialize=input_dict['production_affect_feas'], doc='set of production processes that affect feasibility')
            model.storage_affect_feas     = Set(initialize=input_dict['storage_affect_feas'], doc='set of storage processes that affect feasibility')
            model.demand_mean_affect_feas = Set(initialize=input_dict['demand_mean_affect_feas'], doc='set of demand means that affect feasibility')
            model.demand_peak_affect_feas = Set(initialize=input_dict['demand_peak_affect_feas'], doc='set of demand peaks that affect reliability')

        #-------------- Define Parameters: -------------------------------------------
        model.next_time_slice     = Param(model.t, initialize=input_dict['next_time_slice'])
        model.time_slice_weight   = Param(model.t, initialize=input_dict['time_slice_weight']) # how many hours of the year are represented by this time_slice
        model.time_slice_duration = Param(model.t, initialize=input_dict['time_slice_duration'])
        model.discount_rate       = Param(model.scenarios, initialize=input_dict['discount_rate'])
        # model.time_horizon     = Param(model.scenarios, initialize=input_dict['time_horizon'])
        model.maximum_area        = Param(initialize=input_dict['maximum_area'])
        model.probability         = Param(model.scenarios, initialize=input_dict['probability'])

        ## Products:
        model.allow_lost_load    = Param(model.products, initialize=input_dict['allow_lost_load'])
        model.value_of_lost_load = Param(model.products, initialize=input_dict['value_of_lost_load'])

        ## Production processes:
        model.production_potential_capacity = Param(model.processes_production, initialize=input_dict['production_potential_capacity'], mutable=True)
        model.production_investment_cost    = Param(model.processes_production, model.scenarios, initialize=input_dict['production_investment_cost'])
        model.production_maintenance_cost   = Param(model.processes_production, model.scenarios, initialize=input_dict['production_maintenance_cost'])
        model.production_operational_cost   = Param(model.processes_production, model.scenarios, initialize=input_dict['production_operational_cost'])
        model.production_lifetime           = Param(model.processes_production, model.scenarios, initialize=input_dict['production_lifetime'])
        model.production_area_per_peak_power = Param(model.processes_production, initialize=input_dict['production_area_per_peak_power'], mutable=True)

        model.production_technology_matrix = Param(model.products, model.processes_production, model.t, initialize=input_dict['production_technology_matrix'])

        ## Storage processes:
        model.storage_potential_capacity = Param(model.processes_storage, initialize=input_dict['storage_potential_capacity'], mutable=True)
        model.storage_investment_cost    = Param(model.processes_storage, model.scenarios, initialize=input_dict['storage_investment_cost'])
        model.storage_maintenance_cost   = Param(model.processes_storage, model.scenarios, initialize=input_dict['storage_maintenance_cost'])
        model.storage_lifetime           = Param(model.processes_storage, model.scenarios, initialize=input_dict['storage_lifetime'])

        model.storage_efficiency_deposit    = Param(model.processes_storage, initialize=input_dict['storage_efficiency_deposit'])
        model.storage_efficiency_withdrawal = Param(model.processes_storage, initialize=input_dict['storage_efficiency_withdrawal'])
        model.storage_loss_percent          = Param(model.processes_storage, model.scenarios, initialize=input_dict['storage_loss_percent'])
        model.storage_minimal_level         = Param(model.processes_storage, initialize=input_dict['storage_minimal_level'])
        model.storage_capacity_ratio        = Param(model.products, model.processes_storage, model.scenarios, initialize=input_dict['storage_capacity_ratio'])

        ## Timeseries:
        # Demand timeseries
        model.demand_unscaled    = Param(model.products, model.t, model.scenarios, initialize=input_dict['demand'], doc='unscaled demand per hour')
        model.ts_demand_old_mean = Param(model.products, initialize=input_dict['ts_demand_old_mean'])
        model.ts_demand_old_peak = Param(model.products, initialize=input_dict['ts_demand_old_peak'])
        # for max_overcapacity, introduce the parameter model.demand_scaled:
        if self.optimization_type == 'max_overcapacity':
            # with hasattr(model, 'demand_scaled'), the optimization_type is currently checked in
            # the timeseries_scaling
            model.demand_scaled = Param(model.products, model.t, model.scenarios,
                                        initialize=input_dict['demand'],mutable=True)
        # for all others:
        else:
            model.ts_demand_mean_min = Param(model.products, initialize=input_dict['ts_demand_mean_min'])
            model.ts_demand_mean_max = Param(model.products, initialize=input_dict['ts_demand_mean_max'])
            model.ts_demand_peak_min = Param(model.products, initialize=input_dict['ts_demand_peak_min'])
            model.ts_demand_peak_max = Param(model.products, initialize=input_dict['ts_demand_peak_max'])

        # Pricebuy timeseries
        model.pricebuy_unscaled  = Param(model.products, model.t, model.scenarios, initialize=input_dict['pricebuy'], doc='only used for plotting')
        model.pricebuy_scaled  = Param(model.products, model.t, model.scenarios, initialize=input_dict['pricebuy'], mutable=True)
        model.ts_pricebuy_old_mean = Param(model.products, initialize=input_dict['ts_pricebuy_old_mean'])
        model.ts_pricebuy_old_peak = Param(model.products, initialize=input_dict['ts_pricebuy_old_peak'])

        # pricesell timeseries
        model.pricesell_unscaled  = Param(model.products, model.t, model.scenarios, initialize=input_dict['pricesell'], doc='only used for plotting')
        model.pricesell_scaled = Param(model.products, model.t, model.scenarios, initialize=input_dict['pricesell'], mutable=True)

        # Availability timeseries
        model.production_availability = Param(
            model.processes_production, model.t, model.scenarios,
            initialize=input_dict['production_availability'],
            mutable=True)
        # the following three parameters are not directly used by the optimization. However, they
        # store information about the interpolation of availabilities. 'production_availability' can
        # be mutaded from the outside based on the following three parameters:
        #      production_availability = avail_1st * (1 - scaler) + avail_2nd * scaler
        model.production_availability_interpolate_1st = Param(
            model.processes_avail_interpolation, model.t,
            initialize = input_dict['availability_interpolation_1st_ts'],
            doc = 'The first availability timeseries for interpolation'
        )
        model.production_availability_interpolate_2nd = Param(
            model.processes_avail_interpolation, model.t,
            initialize = input_dict['availability_interpolation_2nd_ts'],
            doc = 'The 2nd availability timeseries for interpolation'
        )
        model.availability_interpolation_scaler = Param(
            model.processes_avail_interpolation, model.scenarios,
            initialize = input_dict['availability_interpolation_scaler'],
            mutable = True
        )

        # Feasibility extreme values
        if self.optimization_type == 'feasible_hull':
            # Production
            model.min_values_production = Param(
                model.production_affect_feas,
                initialize=input_dict['min_values_production'],
                doc='Minimum values of Production variables',
                mutable = True)
            model.max_values_production = Param(
                model.production_affect_feas,
                initialize=input_dict['max_values_production'],
                doc='Maximum values of Production variables',
                mutable = True)

            # Storage
            model.min_values_storage = Param(
                model.storage_affect_feas,
                initialize=input_dict['min_values_storage'],
                doc='Minimum values of Storage variables',
                mutable = True)
            model.max_values_storage = Param(
                model.storage_affect_feas,
                initialize=input_dict['max_values_storage'],
                doc='Maximum values of Storage variables',
                mutable = True)

            # Demand Mean
            model.min_values_demand_mean = Param(
                model.demand_mean_affect_feas,
                initialize=input_dict['min_values_demand_mean'],
                doc='Minimum values of Demand mean variables',
                mutable = True)
            model.max_values_demand_mean = Param(
                model.demand_mean_affect_feas,
                initialize=input_dict['max_values_demand_mean'],
                doc='Maximum values of Demand mean variables',
                mutable = True)

            # Demand peak
            model.min_values_demand_peak = Param(
                model.demand_peak_affect_feas,
                initialize=input_dict['min_values_demand_peak'],
                doc='Minimum values of Demand peak variables',
                mutable = True)
            model.max_values_demand_peak = Param(
                model.demand_peak_affect_feas,
                initialize=input_dict['max_values_demand_peak'],
                doc='Maximum values of Demand peak variables',
                mutable = True)

        # Feasibility search directions
        if self.optimization_type == 'feasible_hull':
            model.search_dir_production = Param(
                model.production_affect_feas,
                initialize=input_dict['default_search_dir_production'], 
                doc = 'Search direction for production process',
                mutable = True)
            model.search_dir_storage = Param(
                model.storage_affect_feas,
                initialize=input_dict['default_search_dir_storage'],
                doc = 'Search direction for storage process',
                mutable = True)

            model.search_dir_demand_mean = Param(
                model.demand_mean_affect_feas,
                initialize=input_dict['default_search_dir_demand_mean'], 
                doc = 'Search direction for demand mean',
                mutable = True)
            model.search_dir_demand_peak = Param(
                model.demand_peak_affect_feas,
                initialize=input_dict['default_search_dir_demand_peak'], 
                doc = 'Search direction for demand peak',
                mutable = True)

        # Near-optimal boundary values (TAC and slack)
        if self.optimization_type == 'near_optimal':
            # TAC of the optimal design
            model.opt_tac = Param(
                initialize=input_dict['opt_tac'],
                doc='Optimal TAC for a scenario; calculated by a design optimization',
                mutable=True
            )
            # Slack for the near-optimal space
            model.slack = Param(
                initialize=input_dict['slack'],
                doc='Slack to set bounds for the near-optimal space',
                mutable=True
            )

            # Near-optimal extreme values
            # Production
            model.min_values_production = Param(
                model.processes_production,
                initialize=input_dict['min_values_production'],
                doc='Minimum values of Production variables',
                mutable = True)
            model.max_values_production = Param(
                model.processes_production,
                initialize=input_dict['max_values_production'],
                doc='Maximum values of Production variables',
                mutable = True)

            # Storage
            model.min_values_storage = Param(
                model.processes_storage,
                initialize=input_dict['min_values_storage'],
                doc='Minimum values of Storage variables',
                mutable = True)
            model.max_values_storage = Param(
                model.processes_storage,
                initialize=input_dict['max_values_storage'],
                doc='Maximum values of Storage variables',
                mutable = True)

            # Near-optimal search directions
            model.search_dir_processes = Param(
                model.processes,
                initialize=input_dict['default_search_dir_processes'],
                doc='Search direction for all processes (production and storage)',
                mutable=True # Is mutated after the model is created
            )

        #-------------- Define Variables: --------------------------------------------
        # Production processes:
        model.Production_prod     = Var(model.products, model.processes_production, model.t, model.scenarios, domain=Reals)
        model.Production_load     = Var(model.processes_production, model.t, model.scenarios, domain=NonNegativeReals)
        model.Production_nominal_capacity = Var(model.processes_production, domain=NonNegativeReals)

        # Storage processes:
        model.Storage_stored_energy    = Var(model.processes_storage, model.t, model.scenarios, domain=NonNegativeReals)
        model.Storage_power_in         = Var(model.products, model.processes_storage, model.t, model.scenarios, domain=NonNegativeReals)
        model.Storage_power_out        = Var(model.products, model.processes_storage, model.t, model.scenarios, domain=NonNegativeReals)
        model.Storage_nominal_capacity = Var(model.processes_storage, domain=NonNegativeReals)

        # Products:
        model.Products_buy       = Var(model.products, model.t, model.scenarios, domain=NonNegativeReals) # kW | hourly purchase of products
        model.Products_sell      = Var(model.products, model.t, model.scenarios, domain=NonNegativeReals) # kW | hourly selling of products
        model.Products_lost_load = Var(model.products, model.t, model.scenarios, domain=NonNegativeReals) # kW | hourly lost load (demand which was not served)

        # Timeseries Scaling:
        model.Demand = Var(model.products, model.t, model.scenarios, domain=NonNegativeReals) # kW | is scaled by a*x + b
        if self.optimization_type != 'max_overcapacity':
            model.Ts_scaler_demand_a = Var(model.products, domain=NonNegativeReals)
            model.Ts_scaler_demand_b = Var(model.products, domain=Reals)
            model.Ts_demand_new_mean = Var(model.products, domain=NonNegativeReals)
            model.Ts_demand_new_peak = Var(model.products, domain=NonNegativeReals)

        # Cost:
        model.OPEX      = Var(model.scenarios, domain=Reals) # Operational Expenditure
        model.CAPEX     = Var(model.scenarios, domain=NonNegativeReals) # Capital Expenditure
        model.TAC       = Var(domain=NonNegativeReals) # Total Annualized cost

        # Overcapacity:
        # the Overcapacity describes, how much larger (or smaller) the maximum servable energy
        # demand would be, compared to the currently assumed energy demand.
        # Overcapacity > 0: The energy system could serve a higher energy demand than assumed
        # Overcapacity = 0: The energy system can JUST serve the assumed energy demand
        # Overcapacity < 0: The energy system can only serve a smaller energy demand than assumed
        model.Overcapacity = Var(domain=Reals, initialize=0)
        # Fix Overcapacity to zero in every optimization mode except for 'max_overcapacity':
        if self.optimization_type != 'max_overcapacity':
            model.Overcapacity.fix(0)

        # Feasibility hull objective functions -  values not relevant
        if self.optimization_type == 'feasible_hull':
            model.Feasible_space      = Var(domain=Reals, doc='Feasibility space value')
            model.Feasible_space_norm = Var(domain=Reals, doc='Normalised feasibility space value')

        # Objectives for the near-optimal space
        if self.optimization_type == "near_optimal":
            model.Near_optimal_space = Var(domain=Reals, doc="Near-optimal space value")
            model.Near_optimal_space_norm = Var(
                domain=Reals, doc="Normalized Near-optimal space value"
            )

        #-------------- Define Constriants: ------------------------------------------
        ##############################################################################
        ####  ENERGY BALANCES                                                    #####
        ##############################################################################

        if self.optimization_type != 'max_overcapacity':
            def energy_balance_rule(model, product, t, scenario):
                return(
                    sum(model.Production_prod[product, production_process, t, scenario] for production_process in model.processes_production)
                    + sum(model.Storage_power_out[product, storage_process, t, scenario] for storage_process in model.processes_storage)
                    + model.Products_buy[product, t, scenario]
                    + model.allow_lost_load[product] * model.Products_lost_load[product, t, scenario]
                    ==
                    sum(model.Storage_power_in[product, storage_process, t, scenario] for storage_process in model.processes_storage)
                    + model.Demand[product, t, scenario] # HERE IS THE DIFFERENCE
                    + model.Products_sell[product, t, scenario]
                )
        else:
            def energy_balance_rule(model, product, t, scenario):
                return(
                    sum(model.Production_prod[product, production_process, t, scenario] for production_process in model.processes_production)
                    + sum(model.Storage_power_out[product, storage_process, t, scenario] for storage_process in model.processes_storage)
                    + model.Products_buy[product, t, scenario]
                    + model.allow_lost_load[product] * model.Products_lost_load[product, t, scenario]
                    ==
                    sum(model.Storage_power_in[product, storage_process, t, scenario] for storage_process in model.processes_storage)
                    + model.demand_scaled[product, t, scenario] * (1 + model.Overcapacity) # HERE IS THE DIFFERENCE
                    + model.Products_sell[product, t, scenario]
                )
        model.energy_balance_rule = Constraint(
            model.products, model.t, model.scenarios,
            rule = energy_balance_rule,
            doc = 'energy balances to satisfy all demands'
        )

        # restrict import and export
        def constraint_restrict_import_rule(model, product, t, scenario):
            """
            This method is used as rule for preventing import of non-importable products.
            """
            if product not in input_dict['importable_products']:
                return(
                    model.Products_buy[product, t, scenario] == 0
                )
            else:
                return Constraint.Skip
        model.constraint_restrict_import_rule = Constraint(
            model.products, model.t, model.scenarios,
            rule = constraint_restrict_import_rule,
            doc = 'restrict import of non-importable products'
        )

        def constraint_restrict_export_rule(model, product, t, scenario):
            """
            This method is used as rule for preventing export of non-exportable products.
            """
            if product not in input_dict['exportable_products']:
                return(
                    model.Products_sell[product, t, scenario] == 0
                )
            else:
                return Constraint.Skip
        model.constraint_restrict_export_rule = Constraint(
            model.products, model.t, model.scenarios,
            rule = constraint_restrict_export_rule,
            doc = 'restrict import of non-exportable products'
        )

        def disable_lost_load_rule(model, product, t, scenario):
            """ Forces Products_lost_load to be zero, if allow_lost_load is zero 
            """
            if not model.allow_lost_load[product]:
                return (model.Products_lost_load[product, t, scenario] == 0)

            return Constraint.Skip

        model.disable_lost_load_rule = Constraint(
            model.products, model.t, model.scenarios,
            rule = disable_lost_load_rule,
            doc = 'restrict import of non-exportable products'
        )
        ##############################################################################
        ####  TIMESERIES SCALING: DEMAND                                         #####
        ##############################################################################


        if self.optimization_type == 'max_overcapacity':
            def demand_variable_parameter_rule(model, product, t, scenario):
                """ This constraint makes sure, that the variable model.Demand is defined for
                'max_overcapacity' optimizations. In this type, model.Demand is not used. In the
                postprocessing, however, model.Demand is needed.
                """
                return (
                    model.Demand[product, t, scenario] == model.demand_scaled[product, t, scenario]
                    )
            model.demand_variable_parameter_rule = Constraint(
                model.products, model.t, model.scenarios,
                rule = demand_variable_parameter_rule,
                doc = 'fixes demand variable'
            )

        # demand timeseries are only scaled for all cases BUT 'max_overcapacity'
        else:
            def ts_demand_scale_rule(model, product, t, scenario):
                return(
                    model.Demand[product, t, scenario]
                    ==
                    model.Ts_scaler_demand_a[product]
                    * model.demand_unscaled[product, t, scenario]
                    + model.Ts_scaler_demand_b[product]
                )
            model.ts_demand_scale_rule = Constraint(
                model.products, model.t, model.scenarios,
                rule = ts_demand_scale_rule,
                doc = 'scales demand timeseries'
            )

            def ts_demand_mean_rule(model, product):
                return(
                    model.Ts_demand_new_mean[product]
                    ==
                    model.Ts_scaler_demand_a[product]
                    * model.ts_demand_old_mean[product]
                    + model.Ts_scaler_demand_b[product]
                )
            model.ts_demand_mean_rule = Constraint(
                model.products,
                rule = ts_demand_mean_rule,
                doc = 'scales mean for demand timeseries'
            )

            def ts_demand_peak_rule(model, product):
                return(
                    model.Ts_demand_new_peak[product]
                    ==
                    model.Ts_scaler_demand_a[product]
                    * model.ts_demand_old_peak[product]
                    + model.Ts_scaler_demand_b[product]
                )
            model.ts_demand_peak_rule = Constraint(
                model.products,
                rule = ts_demand_peak_rule,
                doc = 'scales peak for demand timeseries'
            )

            def ts_demand_peak_mean_rule(model, product):
                return(
                    model.Ts_demand_new_peak[product]
                    >=
                    model.Ts_demand_new_mean[product]
                )
            model.ts_demand_peak_mean_rule = Constraint(
                model.products,
                rule = ts_demand_peak_mean_rule,
                doc = 'demand: peak >= mean'
            )

            # Only for products WITH proportional scaling of mean and peak:
            def ts_demand_fix_b_rule(model, product):
                # skip, if mean and peak can be scaling non-proportionally:
                if product in model.products_demand_nonprop_scaling:
                    return Constraint.Skip

                return(
                    model.Ts_scaler_demand_b[product] == 0
                )
            model.ts_demand_fix_b_rule = Constraint(
                model.products,
                rule = ts_demand_fix_b_rule,
                doc = 'demand: b = 0 for proportional scaling'
            )

            # Fix a and b values for 'classic' optimization:
            for product in model.products:

                # Dont fix values that affect the feasible_hull:
                if self.optimization_type == 'feasible_hull':
                    if product in (model.demand_mean_affect_feas | model.demand_peak_affect_feas):
                        continue

                # Fix mean:
                model.Ts_demand_new_mean[product].fix(model.ts_demand_old_mean[product])
                # Fix peak:
                model.Ts_demand_new_peak[product].fix(model.ts_demand_old_peak[product])

        # Bound min and max values of mean and peak demand only for feasible hull exploration:
        if self.optimization_type == 'feasible_hull':
            def ts_demand_min_mean_rule(model, product):
                return(
                    model.Ts_demand_new_mean[product]
                    >=
                    model.ts_demand_mean_min[product]
                )
            model.ts_demand_min_mean_rule = Constraint(
                model.products,
                rule = ts_demand_min_mean_rule,
                doc = 'demand: mean >= mean_min'
            )

            def ts_demand_max_mean_rule(model, product):
                return(
                    model.ts_demand_mean_max[product]
                    >=
                    model.Ts_demand_new_mean[product]
                )
            model.ts_demand_max_mean_rule = Constraint(
                model.products,
                rule = ts_demand_max_mean_rule,
                doc = 'demand: mean_max >= mean'
            )

            # Only for products WITHOUT proportional scaling of mean and peak:
            def ts_demand_min_peak_rule(model, product):
                return(
                    model.Ts_demand_new_peak[product]
                    >=
                    model.ts_demand_peak_min[product]
                )
            model.ts_demand_min_peak_rule = Constraint(
                model.products_demand_nonprop_scaling,
                rule = ts_demand_min_peak_rule,
                doc = 'demand: peak >= peak_min'
            )

            # Only for products WITHOUT proportional scaling of mean and peak:
            def ts_demand_max_peak_rule(model, product):
                return(
                    model.ts_demand_peak_max[product]
                    >=
                    model.Ts_demand_new_peak[product]
                )
            model.ts_demand_max_peak_rule = Constraint(
                model.products_demand_nonprop_scaling,
                rule = ts_demand_max_peak_rule,
                doc = 'demand: peak_max >= peak'
            )

        ##############################################################################
        ####  COSTS                                                              #####
        ##############################################################################

        def opex_rule(model, scenario):
            return(
                model.OPEX[scenario]
                ==
                sum(
                    (
                        sum(
                            model.Products_buy[product, t, scenario] * model.pricebuy_scaled[product, t, scenario] # bought products
                            - model.Products_sell[product, t, scenario] * model.pricesell_scaled[product, t, scenario] # sold products
                            + model.Products_lost_load[product, t, scenario] * model.value_of_lost_load[product] # cost of lost load
                            for product in model.products
                        )
                        +
                        sum(# cost of operation for each process
                            model.Production_load[production_process, t, scenario] * model.production_operational_cost[production_process, scenario]
                            for production_process in model.processes_production
                        )
                    )* model.time_slice_weight[t] for t in model.t
                )
            )
        model.opex_rule = Constraint(
            model.scenarios,
            rule = opex_rule
        )

        def capex_rule(model, scenario):
            def apvf(discount_rate, lifetime):
                return ( (discount_rate + 1) ** lifetime - 1) / (discount_rate * (discount_rate + 1)**lifetime)

            return(
                model.CAPEX[scenario]
                ==
                sum(
                    model.production_investment_cost[production_process, scenario] * model.Production_nominal_capacity[production_process] / apvf(model.discount_rate[scenario], model.production_lifetime[production_process, scenario])
                    + model.production_investment_cost[production_process, scenario] * model.Production_nominal_capacity[production_process] * model.production_maintenance_cost[production_process, scenario]/ 100
                    for production_process in model.processes_production
                )
                + sum(
                    model.storage_investment_cost[storage_process, scenario] * model.Storage_nominal_capacity[storage_process] / apvf(model.discount_rate[scenario], model.storage_lifetime[storage_process, scenario])
                    + model.storage_investment_cost[storage_process, scenario] * model.Storage_nominal_capacity[storage_process] * model.storage_maintenance_cost[storage_process, scenario]/ 100
                    for storage_process in model.processes_storage
                )
            )
        model.capex_rule = Constraint(
            model.scenarios,
            rule = capex_rule
        )

        def tac_rule(model):
            return(
                model.TAC
                ==
                sum(
                    model.probability[scenario] * ( model.CAPEX[scenario] + model.OPEX[scenario])
                    for scenario in model.scenarios
                )
            )
        model.tac_rule = Constraint(
            rule = tac_rule
        )

        # Near-optimal cost constraint
        if self.optimization_type == 'near_optimal':
            def near_optimal_rule(model):
                return model.TAC <= model.opt_tac * (1 + model.slack)
            model.near_optimal_rule = Constraint(
                rule=near_optimal_rule
        )

        ##############################################################################
        ####  Production Processes                                               #####
        ##############################################################################

        def constraint_production_operational_optimization_max_rule(model, process):
            """ constraints forces production processes to be build for operational optmization.
            The preprocessing defines production_potential_capacity as the nominal capacity found
            in designs.yaml
            """
            if input_dict['objective'] in {'operation', 'max_overcapacity'}:
                return(
                    model.Production_nominal_capacity[process]
                    ==
                    model.production_potential_capacity[process]
                )
            if input_dict['objective'] in {'design', 'feasible_hull', 'near_optimal'}:
                return Constraint.Skip
            raise ValueError(f"Unknown objective '{input_dict['objective']}'.")
        model.constraint_production_operational_optimization_max_rule = Constraint(
            model.processes_production,
            rule = constraint_production_operational_optimization_max_rule
        )

        def constraint_production_partload_rule(model, product, process, t, scenario):
            return(
                model.Production_prod[product, process, t, scenario]
                ==
                model.production_technology_matrix[product, process, t]
                * model.Production_load[process, t, scenario]
            )
        model.constraint_production_partload_rule = Constraint(
            model.products, model.processes_production, model.t, model.scenarios,
            rule = constraint_production_partload_rule
        )

        def constraint_production_maxload_rule(model, process, t, scenario):
            return(
                model.Production_load[process, t, scenario]
                <=
                model.Production_nominal_capacity[process]
            )
        model.constraint_production_maxload_rule = Constraint(
            model.processes_production, model.t, model.scenarios,
            rule = constraint_production_maxload_rule
        )

        def constraint_production_availability_rule(model, process, t, scenario):
            """ this rule constraints the production by the availability."""

            return(
                model.Production_load[process, t, scenario]
                <=
                model.Production_nominal_capacity[process]
                *model.production_availability[process, t, scenario]
            )
        model.constraint_production_availability_rule = Constraint(
            model.processes_production, model.t, model.scenarios,
            rule = constraint_production_availability_rule
        )

        def constraint_production_potential_capacity_rule(model, process):
            """ this rule makes sure, that the nominal_capacitiy is bounded by the
            potential capacity"""
            return(
                model.Production_nominal_capacity[process]
                <=
                model.production_potential_capacity[process]
            )
        model.constraint_production_potential_capacity_rule = Constraint(
            model.processes_production,
            rule = constraint_production_potential_capacity_rule
        )

        def constraint_maximum_solar_area_rule(model):
            """Ensure the total area of PV and Solar collectors does not exceed
            the maximum allowed area only in 'design' mode."""

            if input_dict['objective'] in {'operation', 'max_overcapacity'}:
                return Constraint.Skip

            return (
                sum(
                    model.Production_nominal_capacity[p] * model.production_area_per_peak_power[p]
                    for p in model.processes_production
                )
                <= model.maximum_area
            )
        model.constraint_maximum_solar_area = Constraint(
            rule = constraint_maximum_solar_area_rule
        )

        ##############################################################################
        ####  Storage Processes                                                  #####
        ##############################################################################

        def constraint_storage_operational_optimization_max_rule(model, process):
            """ constraints forces storages to be build for operational optmization.
            The preprocessing defines storage_potential_capacity as the nominal capacity found
            in designs.yaml
            """
            if input_dict['objective'] in {'operation', 'max_overcapacity'}:
                return(
                    model.Storage_nominal_capacity[process]
                    ==
                    model.storage_potential_capacity[process]
                )
            if input_dict['objective'] in {'design', 'feasible_hull', 'near_optimal'}:
                return Constraint.Skip
            raise ValueError(f"Unknown objective '{input_dict['objective']}'.")

        model.constraint_storage_operational_optimization_max_rule = Constraint(
            model.processes_storage,
            rule = constraint_storage_operational_optimization_max_rule
        )

        def constraint_storage_level_limit_by_capacity_rule(model, process, t, scenario):
            """ Constraint #17 in https://doi.org/10.1016/j.compchemeng.2023.108176 """
            return(
                model.Storage_stored_energy[process, t, scenario]
                <=
                model.Storage_nominal_capacity[process]
            )
        model.constraint_storage_level_limit_by_capacity_rule = Constraint(
            model.processes_storage, model.t, model.scenarios,
            rule = constraint_storage_level_limit_by_capacity_rule
        )

        def constraint_storage_level_limit_by_capacity_lower_rule(model, process, t, scenario):
            """ Constraint #18 in https://doi.org/10.1016/j.compchemeng.2023.108176 """
            return(
                model.Storage_stored_energy[process, t, scenario]
                >=
                model.Storage_nominal_capacity[process] * model.storage_minimal_level[process]/100
            )
        model.constraint_storage_level_limit_by_capacity_lower_rule = Constraint(
            model.processes_storage, model.t, model.scenarios,
            rule = constraint_storage_level_limit_by_capacity_lower_rule
        )

        def constraint_storage_capacity_ratio_in(model, product, process, t, scenario):
            """ Constraint #21 in https://doi.org/10.1016/j.compchemeng.2023.108176 """
            return(
                model.Storage_power_in[product, process, t, scenario]
                <=
                model.storage_capacity_ratio[product, process, scenario]
                * model.Storage_nominal_capacity[process]
            )
        model.constraint_storage_capacity_ratio_in = Constraint(
            model.products, model.processes_storage, model.t, model.scenarios,
            rule = constraint_storage_capacity_ratio_in
        )

        def constraint_storage_capacity_ratio_out(model, product, process, t, scenario):
            """ Constraint #22 in https://doi.org/10.1016/j.compchemeng.2023.108176 """
            return(
                model.Storage_power_out[product, process, t, scenario]
                <=
                model.storage_capacity_ratio[product, process, scenario]
                * model.Storage_nominal_capacity[process]
            )
        model.constraint_storage_capacity_ratio_out = Constraint(
            model.products, model.processes_storage, model.t, model.scenarios,
            rule = constraint_storage_capacity_ratio_out
        )

        def constraint_storage_potential_capacity_rule(model, process):
            """ Constraint #15 in https://doi.org/10.1016/j.compchemeng.2023.108176.
            Here, the binary variable is removed.
            """
            return(
                model.Storage_nominal_capacity[process]
                <=
                model.storage_potential_capacity[process]
            )
        model.constraint_storage_potential_capacity_rule = Constraint(
            model.processes_storage,
            rule = constraint_storage_potential_capacity_rule
        )

        def constraint_storage_level_rule(model, product, process, t, scenario):
            """ Constraint #19 in https://doi.org/10.1016/j.compchemeng.2023.108176 """
            # If product is not the reference product, skip Constraint, since this constraint
            # is only indented for the reference product:
            if input_dict['storage_reference'][process] != product:
                return Constraint.Skip

            return(
                # sum of the current storage level, the deposits and withdrawals
                # current storage level:
                (
                    model.Storage_stored_energy[process, t, scenario]
                    *(1-model.storage_loss_percent[process, scenario]/100)
                    **model.time_slice_duration[t]
                # deposits: multiply the time slice duration with the storage deposits 
                    + (
                        model.time_slice_duration[t]
                        * model.Storage_power_in[product, process, t, scenario]
                        * model.storage_efficiency_deposit[process]
                        )
                # withdrawals: multiply the time slice duration with the storage withdrawals
                - (
                    model.time_slice_duration[t]
                    * model.Storage_power_out[product, process, t, scenario]
                    / model.storage_efficiency_withdrawal[process]
                    )
                )
                # the sum above equal the storage level of the next time slice
                ==
                model.Storage_stored_energy[process, model.next_time_slice[t], scenario]
            )
        model.constraint_storage_level_rule = Constraint(
            model.products, model.processes_storage, model.t, model.scenarios,
            rule = constraint_storage_level_rule
        )

        ##############################################################################
        ####  Feasibility Hull                                                   #####
        ##############################################################################

        if self.optimization_type == 'feasible_hull':
            def feasible_space_rule(model):
                return(
                    model.Feasible_space
                    ==
                    sum(model.search_dir_production[tec]*model.Production_nominal_capacity[tec]
                    for tec in model.production_affect_feas)
                    + sum(model.search_dir_storage[tec] * model.Storage_nominal_capacity[tec]
                    for tec in model.storage_affect_feas)
                    + sum(model.search_dir_demand_mean[p] * model.Ts_demand_new_mean[p]
                    for p in model.demand_mean_affect_feas)
                    + sum(model.search_dir_demand_peak[p] * model.Ts_demand_new_peak[p]
                    for p in model.demand_peak_affect_feas)
                )

            model.feasible_space_rule = Constraint(
                rule = feasible_space_rule
            )

            def feasible_space_norm_rule(model):
                return(
                    model.Feasible_space_norm
                    ==
                    sum(
                        model.search_dir_production[tec] *
                        (model.Production_nominal_capacity[tec] - model.min_values_production[tec])/
                        (model.max_values_production[tec] - model.min_values_production[tec])
                        for tec in model.production_affect_feas
                    )
                    + sum(
                        model.search_dir_storage[tec] *
                        (model.Storage_nominal_capacity[tec] - model.min_values_storage[tec]) /
                        (model.max_values_storage[tec] - model.min_values_storage[tec])
                        for tec in model.storage_affect_feas
                    )
                    + sum(
                        model.search_dir_demand_mean[p] *
                        (model.Ts_demand_new_mean[p] - model.min_values_demand_mean[p]) /
                        (model.max_values_demand_mean[p] - model.min_values_demand_mean[p])
                        for p in model.demand_mean_affect_feas
                    )
                    + sum(
                        model.search_dir_demand_peak[p] *
                        (model.Ts_demand_new_peak[p] - model.min_values_demand_peak[p]) /
                        (model.max_values_demand_peak[p] - model.min_values_demand_peak[p])
                        for p in model.demand_peak_affect_feas
                    )
                )

            model.feasible_space_norm_rule = Constraint(
                rule = feasible_space_norm_rule
            )

        ##############################################################################
        ####  Near-optimal                                                       #####
        ##############################################################################

        if self.optimization_type == "near_optimal":
            def near_optimal_space_rule(model):
                return (
                    model.Near_optimal_space ==
                    sum(
                        model.search_dir_processes[proc] *
                        model.Production_nominal_capacity[proc]
                        for proc in model.processes_production
                    ) +
                    sum(
                        model.search_dir_processes[proc] *
                        model.Storage_nominal_capacity[proc]
                        for proc in model.processes_storage
                    )
                )
            model.near_optimal_space_rule = Constraint(
                rule=near_optimal_space_rule
            )

            def near_optimal_space_norm_rule(model):
                return (
                    model.Near_optimal_space_norm ==
                    sum(
                        model.search_dir_processes[proc] *
                        (model.Production_nominal_capacity[proc] - model.min_values_production[proc]) /
                        (model.max_values_production[proc] - model.min_values_production[proc])
                        for proc in model.processes_production
                    ) +
                    sum(
                        model.search_dir_processes[proc] *
                        (model.Storage_nominal_capacity[proc] - model.min_values_storage[proc]) /
                        (model.max_values_storage[proc] - model.min_values_storage[proc])
                        for proc in model.processes_storage
                    )
                )
            model.near_optimal_space_norm_rule = Constraint(
                rule=near_optimal_space_norm_rule
            )

        #-------------- Objective Function: ------------------------------------------

        # max overcapacity: only for max_overcapacity:
        if self.optimization_type == 'max_overcapacity':
            def rule_objective_constraint(model):
                return model.Overcapacity
            model.obj = Objective(rule=rule_objective_constraint, sense=maximize)

        # feasible_space: only for feasible_hull:
        elif self.optimization_type == 'feasible_hull':
            def rule_objective_constraint(model):
                return model.Feasible_space_norm
            model.obj = Objective(rule=rule_objective_constraint, sense=maximize)

        # near_optimal_space: only for near_optimal:
        elif self.optimization_type == 'near_optimal':
            def rule_objective_constraint(model):
                return model.Near_optimal_space_norm
            model.obj = Objective(rule=rule_objective_constraint, sense=maximize)

        # min TAC: for all optimization_types except for max_overcapacity:
        else:
            def rule_objective_constraint(model):
                return model.TAC
            model.obj = Objective(rule=rule_objective_constraint)

        return model

class Optimization_MILP(Optimization):
    """
    Child of Optimization() for MILPs.
    """
    def __init__(self, data_in_path, project_file:str, input_dict:dict):
        """
        Args:
            data_in_path (str): path to the input data (containing the project file)
            project_file (str): name of the .yaml file in data_in_path containing the
                input information (e.g. project.yaml)
            input_dict (dict): scaled input_dict generated by preprocessing.ScaledInputDictGenerator
        """
        super().__init__(data_in_path, project_file, input_dict)

        self.model_formulation = 'MILP'
        # Warn, if another model_formulation than 'MILP' is given in config.yaml:
        model_formulation = get_config_file(data_in_path, project_file)['model_formulation']
        if model_formulation != 'MILP':
            warnings.warn(
                f"Unexpected model_formulation for Optimiation_MILP: '{model_formulation}' " +
                "instead of 'MILP'")

    def generate_model(self):
        """ Generates the pyomo model for the given input data.

        Returns:
            pyomo.ConcreteModel: The generated model.
        """
        print(f"Generating MILP model... ({self.optimization_type})")
        input_dict = self.input_dict
        model = ConcreteModel()

        #-------------- Define Sets: -------------------------------------------------
        model.t                    = Set(initialize=input_dict['time_slices'], doc='time slices')
        model.processes_production = Set(initialize=input_dict['processes_production'], doc='set of production processes')
        model.processes_avail_interpolation = Set(initialize=input_dict['processes_availability_interpolation'],doc='processes, where the availability can be interpolated.')
        model.processes_storage    = Set(initialize=input_dict['processes_storage'], doc='set of storage processes')
        model.products             = Set(initialize=input_dict['products'], doc='set of products')
        model.scenarios            = Set(initialize=input_dict['scenarios'], doc='set of scenarios')

        # Search directions:
        model.products_demand_nonprop_scaling = Set(
            initialize = input_dict['products_demand_nonprop_scaling'],
            doc        = 'set of products, where mean and peak do not scale proportionally for the demand timeseries scaling.'
        )

        #-------------- Define Parameters: -------------------------------------------
        model.next_time_slice     = Param(model.t, initialize=input_dict['next_time_slice'])
        model.time_slice_weight   = Param(model.t, initialize=input_dict['time_slice_weight']) # how many hours of the year are represented by this time_slice
        model.time_slice_duration = Param(model.t, initialize=input_dict['time_slice_duration'])
        model.discount_rate       = Param(model.scenarios, initialize=input_dict['discount_rate'])
        # model.time_horizon     = Param(model.scenarios, initialize=input_dict['time_horizon'])
        model.probability         = Param(model.scenarios, initialize=input_dict['probability'])

        # Products:
        model.allow_lost_load    = Param(model.products, initialize=input_dict['allow_lost_load'])
        model.value_of_lost_load = Param(model.products, initialize=input_dict['value_of_lost_load'])

        # Production processes:
        model.production_minimal_capacity   = Param(model.processes_production, initialize=input_dict['production_minimal_capacity'], mutable=True)
        model.production_potential_capacity = Param(model.processes_production, initialize=input_dict['production_potential_capacity'], mutable=True)
        model.production_investment_cost    = Param(model.processes_production, model.scenarios, initialize=input_dict['production_investment_cost'])
